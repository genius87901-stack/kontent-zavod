def сохранённый_код():
    """Уже заведённый код — тем же чтением, каким его берёт публикация."""
    if config_reader is not None:
        try:
            значение = config_reader.value(KEY_NAME, start=HERE)
            if значение:
                return значение.strip()
        except Exception:                                    # noqa: BLE001
            pass
    свой = os.environ.get(KEY_NAME)
    return свой.strip() if свой and свой.strip() else None


def сохранить_код(код: str) -> Path:
    """Дописать код в `.env`, НЕ трогая остальные строки.

    Формат тот же, что пишет install/setup_config.py::write_env: имя в
    UPPER_SNAKE, файл со шляпкой-предупреждением, права 0600. Разойтись с
    мастером установки форматом нельзя — читать это будут одни и те же глаза.
    """
    путь = путь_секретов()
    путь.parent.mkdir(parents=True, exist_ok=True)
    было: dict = {}
    if путь.exists():
        for строка in путь.read_text(encoding="utf-8-sig").splitlines():
            строка = строка.strip()
            if строка and not строка.startswith("#") and "=" in строка:
                k, v = строка.split("=", 1)
                было[k.strip().upper()] = v.strip()
    было[KEY_NAME] = код
    тело = "# Секреты «Контент-завода». НЕ коммитить. Правит только установщик.\n"
    тело += "\n".join("%s=%s" % (k, v) for k, v in sorted(было.items())) + "\n"
    путь.write_text(тело, encoding="utf-8")
    try:
        os.chmod(путь, 0o600)         # на Windows пусто, на Unix обязательно
    except OSError:
        pass
    return путь


def сохранить_сводку(страницы) -> Path:
    """Несекретная строка «что подключено» — рядом с прочими ответами клиента.

    Слияние, а не запись поверх: конфиг общий, и затереть чужие ответы значит
    отменить всю прошлую установку. Ровно так же поступает setup_config.
    """
    цели = sorted({"%s:%s" % (с.get("social"), с.get("type")) for с in страницы
                   if с.get("social") and с.get("type")})
    путь = путь_конфига()
    путь.parent.mkdir(parents=True, exist_ok=True)
    было: dict = {}
    if путь.exists():
        try:
            прочитано = json.loads(путь.read_text(encoding="utf-8-sig"))
            if isinstance(прочитано, dict):
                было.update(прочитано)
        except (OSError, ValueError):
            pass
    было[СВОДКА_КЛЮЧ] = ",".join(цели)
    путь.write_text(json.dumps(было, ensure_ascii=False, indent=2, sort_keys=True),
                    encoding="utf-8")
    return путь


# ── ПРОВЕРКА КОДА ЖИВЬЁМ ────────────────────────────────────────────────────
def спросить_страницы(код: str):
    """Единственный сетевой шаг: «покажи, чьи страницы подключены под этим кодом».

    Возвращает (исход, данные). Исход — наше слово, а не чужое: сырой ответ
    сервиса дальше этой функции не идёт. Читающий запрос, ничего не меняет и
    ничего не публикует.
    """
    _sandbox_guard()
    заголовки = {"Authorization": "Bearer %s" % код, "Accept": "application/json"}
    try:
        ответ = _request("GET", "%s/groups" % СЛУЖБА,
                         headers=заголовки, timeout=TIMEOUT)
    except RuntimeError:
        return "нет_библиотеки", None
    except Exception:                                        # noqa: BLE001
        return "нет_связи", None

    статус = getattr(ответ, "status_code", 0)
    if статус in (401, 403):
        return "не_тот_код", None
    try:
        данные = ответ.json()
    except Exception:                                        # noqa: BLE001
        return "отказ_сервиса", None
    if not isinstance(данные, dict) or not данные.get("success"):
        return "отказ_сервиса", None
    ответы = данные.get("response") or []
    if not isinstance(ответы, list):
        return "отказ_сервиса", None
    return "ок", [с for с in ответы if isinstance(с, dict)]


