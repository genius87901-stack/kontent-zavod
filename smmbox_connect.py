"""ПОДКЛЮЧЕНИЕ SmmBox ОДНОЙ ФРАЗОЙ КЛИЕНТА — мастер, который ведёт по шагам.

ЗАЧЕМ ЭТОТ ФАЙЛ. Публиковать через SmmBox умеет smmbox_post.py, но для этого
нужен ключ из чужого кабинета. Спросить его анкетой мастера установки нельзя:
человек не знает ни слова «токен», ни где у стороннего сервиса лежат настройки
аккаунта, ни того, что доступ там платный. Ровно на этом люди застревали с ВК —
анкета спрашивала VK_APP_ID и токен, и человек упирался в тупик. Лечение уже
найдено и работает: `vk_auth.py --kate` / `--kate-finish` — не вопрос анкеты, а
ШАГ, который ведёт клиента и сам всё записывает. Здесь повторён тот же приём, а
не изобретён новый.

ПЕРВЫМ ДЕЛОМ — ДЕНЬГИ. Работа из программ у SmmBox включена с тарифа «Эксперт
(VIP)» и выше; на «Старт» и «Профи» её нет вовсе, причём код доступа выдают и
там — отказ приходит уже на публикации. То есть человек может завести аккаунт,
пройти все шаги и узнать про деньги последним. Поэтому предупреждение стоит
ПЕРВЫМ экраном, до любых вопросов и до всякой регистрации: у человека должна
быть возможность сказать «нет» раньше, чем он что-то сделал. Это прямое
распоряжение владельца, а не вежливость, и оно заперто тестом.

ПОЧЕМУ ЗДЕСЬ НЕТ ВОПРОСОВ В ТЕРМИНАЛ. CONTRACT.md §3 запрещает интерактивный ввод внутри
модулей: все вопросы задаёт помощник клиента, а модуль получает ответ
аргументом. Тот же расклад, что у `vk_auth.py --kate-finish "<адрес>"`. Иначе
шаг нельзя встроить в мастер и нельзя проверить тестом.

ПРОВЕРКА ЖИВЬЁМ, А НЕ НА ВЕРУ. Записать код и понадеяться — значит отдать
человеку зелёный отчёт и падающую публикацию (так уже было с ключами, что
уезжали в один файл, а читались из другого, — см. modules/publishing/
config_reader.py). Поэтому код сперва предъявляется сервису запросом списка
подключённых страниц, и только принятый код сохраняется. Заодно человек видит
СВОИ страницы человеческими словами — это и есть ответ на вопрос «а подключилось
ли».

ЧТО ГОВОРИТСЯ ПРИ ОТКАЗЕ. Не ответ сервиса. Клиенту нужны его действия, а не
чужая формулировка: не тот код / тариф не тот / страницы не подключены. Сырой
ответ в переписку не уходит вовсе.

КУДА ПИШЕМ. Ровно туда же, куда мастер установки: код — в `.env` (секрет,
права 0600, в переписке не показывается никогда), несекретная сводка — в
`config/factory.config.json`. Пути спрашиваем у modules/publishing/
config_reader.py — того же ридера, которым читают публикация и доктор. Свой
поиск корня здесь завёл бы второе место хранения, а это уже было живым дефектом.

ПРО КНОПКУ КОПИРОВАНИЯ — ОТДЕЛЬНО, ЭТО ЖИВАЯ ГРАБЛЯ. Страница настроек
показывает код СОКРАЩЁННО: начало, точки посередине, хвост. Человек видит
строку целиком глазами, выделяет её мышью — и присылает огрызок, потому что
выделяется ровно то, что нарисовано, вместе с точками. Так и вышло 25.08.2026 у
первого же клиента: первая попытка была обрезанной, а мастер тогда честно
ответил «код не подошёл» — совет «скопируйте целиком» ничем не помогал, ведь
человек и так копировал всё, что видел. Рядом с кодом есть кнопка копирования,
и только она кладёт в буфер настоящую строку. Поэтому про кнопку сказано и в
шагах, и первой причиной в объяснении отказа, а не оставлено на догадку.

КОДЫ ВОЗВРАТА (CONTRACT.md §2 — степень беды, а не «да/нет»):
    0 — подключено: код принят сервисом, страницы видны, настройки записаны;
    2 — не подключено, но бросать всё и чинить не нужно: код не подошёл, тариф
        не тот, страниц нет, сервис не ответил. Остальной завод работает;
    1 — сломан сам мастер: нечем сходить в сеть, не смог записать настройки.

ЗАПУСК (все три команды зовёт помощник, клиент говорит словами):
    python smmbox_connect.py                  # предупреждение и шаги, в сеть НЕ ходит
    python smmbox_connect.py --finish "<код>" # проверить код живьём и записать
    python smmbox_connect.py --check          # перепроверить уже сохранённый код

ТЕСТЫ: python run_tests.py --only smmbox_connect
"""
