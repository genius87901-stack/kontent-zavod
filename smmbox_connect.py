def _utf8() -> None:
    """Консоль русской Windows — cp1251, и любой значок вне неё роняет вывод."""
    for поток in (sys.stdout, sys.stderr):
        try:
            поток.reconfigure(encoding="utf-8", errors="replace")
        except Exception:                                    # noqa: BLE001
            pass


# ── ЕДИНСТВЕННАЯ ДВЕРЬ НАРУЖУ ───────────────────────────────────────────────
def _настоящий_запрос(method, url, **kw):
    """Одна функция на весь мастер — её и подменяют тесты.

    Тот же приём, что у smmbox_post.py и стенда генерации: пока настоящая дверь
    на месте, под предохранителем тестов мастер отказывается работать вовсе.
    """
    if requests is None:
        raise RuntimeError("нет библиотеки связи")
    return requests.request(method, url, **kw)


_request = _настоящий_запрос


def _sandbox_guard() -> None:
    """Под тестами наружу не ходим, даже если код достали из файла мимо окружения."""
    if os.environ.get("KARUSEL_TESTS_SANDBOX") == "1" and _request is _настоящий_запрос:
        sys.exit("ОТКАЗ: прогон под предохранителем тестов, а дверь наружу НЕ "
                 "подменена. Настоящих обращений к сервису здесь не бывает.")


# ── ГДЕ ЛЕЖАТ НАСТРОЙКИ (спрашиваем у общего ридера, своего места не заводим) ─
def корень() -> Path:
    if config_reader is not None:
        try:
            return Path(config_reader.root(start=HERE))
        except Exception:                                    # noqa: BLE001
            pass
    свой = os.environ.get("FACTORY_ROOT")
    if свой and Path(свой).exists():
        return Path(свой)
    for кандидат in (HERE, *HERE.parents):
        for маркер in (".factory_root", "config/factory.config.json",
                       "modules", "CONTRACT.md"):
            if (кандидат / маркер).exists():
                return кандидат
    return Path.cwd()


