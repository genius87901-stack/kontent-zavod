# СБОРКА РЕЕСТРА ИЗ КОДА
# ═══════════════════════════════════════════════════════════════════════════
#: Файлы, которые попадают под маску `engine*.py`, но движками не являются.
#: Пока это только сам переходник: он лежит рядом с движками, потому что зовут
#: его оттуда же, откуда и их.
#:
#: ВНИМАНИЕ ВЛАДЕЛЬЦУ ДЫМОВЫХ ТЕСТОВ. Ту же маску `engine*.py` берёт с диска
#: test_engines_smoke.py (test_registry_covers_every_engine_on_disk) — и,
#: в отличие от этого места, исключений у него нет: появление ЛЮБОГО файла
#: `engine*.py`, который не движок, роняет его проверку. Правится одной
#: строкой в том тесте (исключить не-движки так же, как здесь); этот модуль
#: чужие тесты не трогает.
НЕ_ДВИЖКИ = (Path(__file__).stem,)


def движки() -> tuple:
    """Все движки завода — с ДИСКА, а не из переписанного руками списка."""
    return tuple(sorted(p.stem for p in КОРЕНЬ.glob("engine*.py")
                        if p.stem not in НЕ_ДВИЖКИ))


def _выбрать_вход(модуль):
    """Найти слайд-функцию, которой движок рисует кадр общей формы.

    Правило (в порядке применения):
      1. подсказка из ПОДСКАЗКИ_ВХОДА — там, где имени `cover*` нет вовсе;
      2. функция ровно `cover` — так у 16 движков из 21;
      3. самая простая из `cover*` (меньше обязательных параметров, при
         равенстве — по алфавиту): у engine_white их три —
         cover_ref/cover_top/cover_marker, и общей форме нужна та, что просит
         меньше родных подробностей.
    Возвращает (функция, имя, причина_подсказки) или (None, None, причина отказа).
    """
    имя_движка = модуль.__name__
    if имя_движка in ПОДСКАЗКИ_ВХОДА:
        имя, почему = ПОДСКАЗКИ_ВХОДА[имя_движка]
        fn = getattr(модуль, имя, None)
        if fn is None or not callable(fn):
            return None, None, f"подсказка указывает на {имя}, которого нет"
        return fn, имя, почему

    fn = getattr(модуль, "cover", None)
    if callable(fn) and inspect.getmodule(fn) is модуль:
        return fn, "cover", ""

    кандидаты = []
    for имя, об in vars(модуль).items():
        if (имя.startswith("cover") and callable(об)
                and inspect.getmodule(об) is модуль):
            обязательных = sum(
                1 for p in inspect.signature(об).parameters.values()
                if p.default is inspect.Parameter.empty)
            кандидаты.append((обязательных, имя, об))
    if not кандидаты:
        return None, None, ("нет ни функции cover*, ни подсказки входа — "
                            "движок не сводится к общей форме")
    кандидаты.sort(key=lambda к: (к[0], к[1]))
    _, имя, об = кандидаты[0]
    return об, имя, ""


def _размер(модуль) -> tuple:
    """Заявленный размер кадра — из самого движка, не литералом.

    W/H — карусель (1080x1350), VW/VH — Reels (1080x1920). Поменяется формат
    завода — переходники поедут вместе с ним, а не против него.
    """
    if hasattr(модуль, "W") and hasattr(модуль, "H"):
        return (модуль.W, модуль.H)
    if hasattr(модуль, "VW") and hasattr(модуль, "VH"):
        return (модуль.VW, модуль.VH)
    import engine4
    return (engine4.W, engine4.H)


def _собрать(имя_движка: str) -> Переходник:
    """Построить переходник по ЖИВОЙ сигнатуре движка."""
    модуль = importlib.import_module(имя_движка)
    fn, имя_входа, почему = _выбрать_вход(модуль)
    if fn is None:
        raise ОтказПереходника(f"{имя_движка}: {почему}")

    план, умеет, надо, родные = [], set(), set(), []
    for имя, п in inspect.signature(fn).parameters.items():
        if п.kind in (inspect.Parameter.VAR_POSITIONAL,
                      inspect.Parameter.VAR_KEYWORD):
            continue
        обязателен = п.default is inspect.Parameter.empty
        if имя in ВЫХОДНЫЕ:
            план.append((имя, ("выход", None)))
            continue
        if (имя_движка, имя) in СБОРЩИКИ:
            план.append((имя, ("сборщик", None)))
            continue
        понятие = ПОНЯТИЕ_ПАРАМЕТРА.get(имя)
        if понятие is not None:
            план.append((имя, ("понятие", понятие)))
            умеет.add(понятие)
            if обязателен and понятие in ОБЯЗАТЕЛЬНЫЕ_ПОНЯТИЯ:
                надо.add(понятие)
            continue
        if обязателен:
            # Родное поле движка. Пустая строка — не «потеря текста» общей
            # формы, а отсутствие детали, которой в общей форме нет вовсе.
            план.append((имя, ("родное", "")))
            родные.append(имя)

    вид = "файл" if any(и in ВЫХОДНЫЕ for и, _ in план) else "образ"
    возм = Возможности(
        движок=имя_движка, вход=имя_входа, размер=_размер(модуль), вид=вид,
        умеет=frozenset(умеет), надо=frozenset(надо), родные=tuple(родные),
        почему_вход=почему)
    return Переходник(возможности=возм, _функция=fn, _план=tuple(план))


_РЕЕСТР: dict = {}
_НЕСВЕДЁННЫЕ: dict = {}


def реестр() -> dict:
    """Все переходники завода: имя движка → Переходник.

    Строится лениво и один раз: импорт 21 движка стоит секунды, и платить их
    тому, кто просто спросил список имён, незачем.
    """
    if not _РЕЕСТР and not _НЕСВЕДЁННЫЕ:
        for имя in движки():
            try:
                _РЕЕСТР[имя] = _собрать(имя)
            except Exception as exc:                        # noqa: BLE001
                # Не роняем весь реестр из-за одного движка: несведённый
                # движок — это результат, который видно (см. несведённые()),
                # а не повод оставить сборщика без остальных двадцати.
                _НЕСВЕДЁННЫЕ[имя] = f"{type(exc).__name__}: {exc}"
    return dict(_РЕЕСТР)


def несведённые() -> dict:
    """Движки, которые под общую форму не легли, и почему."""
    реестр()
    return dict(_НЕСВЕДЁННЫЕ)


def переходник(имя: str) -> Переходник:
    р = реестр()
    if имя not in р:
        причина = несведённые().get(имя)
        if причина:
            raise ОтказПереходника(f"{имя} не сведён к общей форме: {причина}")
        raise ОтказПереходника(
            f"движка {имя} нет среди {', '.join(движки())}")
    return р[имя]


def возможности(имя: str) -> Возможности:
    """Паспорт движка: что умеет, что требует, какого размера кадр отдаёт."""
    return переходник(имя).возможности


def нарисовать(имя: str, слайд: Слайд, выход=None, опустить=()):
    """Позвать движок ОДНОЙ формой. Ради этой строки всё и затевалось."""
    return переходник(имя).нарисовать(слайд, выход, опустить)


def умеют(понятие: str) -> tuple:
    """Движки, которым это понятие можно передавать. Для выбора движка под
    материал: есть подзаголовок — вот те, кто его не потеряет."""
    return tuple(имя for имя, п in sorted(реестр().items())
                 if понятие in п.возможности.умеет)
