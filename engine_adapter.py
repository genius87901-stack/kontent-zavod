class ОтказПереходника(ValueError):
    """Движок не умеет то, что ему передали, — и говорит об этом вслух.

    Наследник ValueError не случайно: движки завода отказываются по-русски
    именно ValueError'ом («текст не влезает даже минимальным кеглем»), и
    сборочные скрипты уже умеют такой отказ ловить.
    """


@dataclass(frozen=True)
class Слайд:
    """Один слайд в общей форме — то, что сборщик знает о кадре ДО движка.

    Всё необязательно: незаполненное понятие просто не передаётся движку, и
    тот рисует по своим умолчаниям. Заполненное — либо доезжает до кадра,
    либо превращается в отказ. Третьего (тихой потери) нет.
    """
    заголовок: str = ""
    подзаголовок: str = ""
    номер: int = 1
    всего: int = 1
    картинка: str | None = None          # ключ в engine4.PHOTOS
    акцент: tuple = (94, 214, 184)       # engine4.ACCENTS["mint"]
    кадры: tuple = ()                    # кадры ролика для видеослоёв
    #: Родные поля конкретного движка (count_label, scene, author…). Общая
    #: форма их не знает и знать не должна — но и не прячет: имена объявлены
    #: в `Возможности.родные`, а чужое имя ловится отказом, а не опечаткой.
    родное: dict = field(default_factory=dict)

    def заявленные(self) -> frozenset:
        """Какие понятия сборщик РЕАЛЬНО заявил в этом слайде.

        Счётчик считается заявленным только когда он осмыслен (всего > 1 или
        номер > 1): иначе каждый одиночный кадр требовал бы от движка «1/1».
        Акцент заявлен всегда — цвет есть у кадра в любом случае.
        """
        н = {АКЦЕНТ}
        if (self.заголовок or "").strip():
            н.add(ЗАГОЛОВОК)
        if (self.подзаголовок or "").strip():
            н.add(ПОДЗАГОЛОВОК)
        if self.всего > 1 or self.номер > 1:
            н.add(СЧЁТЧИК)
        if self.картинка is not None:
            н.add(КАРТИНКА)
        if self.кадры:
            н.add(КАДРЫ)
        return frozenset(н)


@dataclass(frozen=True)
class Возможности:
    """Паспорт движка: что он умеет, чего требует и что отдаёт.

    Собирается ИЗ ЖИВОЙ СИГНАТУРЫ, а не записывается руками, — иначе разойдётся
    с кодом при первой же правке движка.
    """
    движок: str
    вход: str                       # имя слайд-функции движка
    размер: tuple                   # (ширина, высота) заявленного кадра
    вид: str                        # "файл" — сохраняет; "образ" — отдаёт PIL
    умеет: frozenset                # понятия общей формы, которые доезжают
    надо: frozenset                 # понятия, без которых движок не нарисует
    родные: tuple                   # обязательные родные поля движка
    почему_вход: str = ""           # если вход выбран подсказкой — причина

    @property
    def не_умеет(self) -> frozenset:
        """Понятия общей формы, которых у движка нет. Не косметика: именно по
        этому набору сборщик выбирает движок под материал, а не наоборот."""
        return frozenset(ПОНЯТИЯ) - self.умеет


@dataclass(frozen=True)
class Переходник:
    """Переходник одного движка: общая форма → родной вызов."""
    возможности: Возможности
    _функция: object
    _план: tuple                    # ((имя параметра, источник), …)

    @property
    def имя(self) -> str:
        return self.возможности.движок

    # ── проверка до вызова ────────────────────────────────────────────────
    def проверить(self, слайд: Слайд, выход=None, опустить=()) -> None:
        """Поднять понятный отказ, если слайд не ложится на движок.

        Отдельный публичный метод, а не внутренность `нарисовать`: сборщику
        нужно уметь спросить «пойдёт ли этот материал на этот движок» ДО
        рендера, чтобы выбрать другой, а не ловить исключение посреди сборки.
        """
        в = self.возможности
        опустить = frozenset(опустить)

        лишние = (слайд.заявленные() - в.умеет) - опустить
        if лишние:
            подсказка = (f"; родные поля движка: {', '.join(в.родные)}"
                         if в.родные else "")
            raise ОтказПереходника(
                f"{в.движок}.{в.вход} не умеет: {', '.join(sorted(лишние))}. "
                f"Текст потерялся бы молча, поэтому кадр не рисуется. Возьми "
                f"движок, у которого это есть, или разреши потерю явно: "
                f"нарисовать(..., опустить={{{', '.join(repr(п) for п in sorted(лишние))}}})"
                f"{подсказка}")

        нет = в.надо - слайд.заявленные()
        if нет:
            raise ОтказПереходника(
                f"{в.движок}.{в.вход} без этого не нарисует: "
                f"{', '.join(sorted(нет))} — заполни в общей форме")

        чужие = set(слайд.родное) - set(self._имена_параметров())
        if чужие:
            raise ОтказПереходника(
                f"{в.движок}.{в.вход}: таких родных полей у движка нет — "
                f"{', '.join(sorted(чужие))}. Есть: "
                f"{', '.join(self._имена_параметров()) or '—'}")

        закреплено = set(слайд.родное) & set(ЗАКРЕПЛЁННЫЕ.get(self.имя, {}))
        if закреплено:
            raise ОтказПереходника(
                f"{в.движок}.{в.вход}: {', '.join(sorted(закреплено))} "
                f"закреплён переходником и всё равно не доехал бы — общая "
                f"форма обязана отдавать кадр заявленного размера. Зови движок "
                f"родным вызовом, если нужно иначе")

        if в.вид == "файл" and выход is None:
            raise ОтказПереходника(
                f"{в.движок}.{в.вход} сохраняет кадр в файл — нужен путь "
                f"вывода (параметр `выход`)")

    def _имена_параметров(self) -> tuple:
        return tuple(inspect.signature(self._функция).parameters)

    # ── сам вызов ─────────────────────────────────────────────────────────
    def аргументы(self, слайд: Слайд, выход=None) -> dict:
        """Разложить общую форму в родные аргументы движка."""
        kwargs = {}
        заявлено = слайд.заявленные()
        for имя, источник in self._план:
            вид, деталь = источник
            if вид == "выход":
                kwargs[имя] = str(выход)
            elif вид == "сборщик":
                kwargs[имя] = СБОРЩИКИ[(self.имя, имя)](слайд)
            elif вид == "родное":
                # Родное поле движка: берём только явно переданное, иначе
                # пустая строка — движок нарисует кадр без этой детали.
                kwargs[имя] = слайд.родное.get(имя, деталь)
            elif вид == "понятие":
                # Незаявленное понятие в НЕобязательный слот не кладём: пусть
                # работает умолчание движка, оно осмысленнее нашей пустоты.
                if деталь not in заявлено and not _обязателен(self._функция, имя):
                    continue
                kwargs[имя] = _значение_понятия(имя, деталь, слайд)
        # Родные поля кладутся ПОСЛЕ плана и поверх него: переданы явно —
        # значит, доехали. Иначе необязательное родное поле (chip у
        # engine_data, eyebrow_text у engine_brutalist) молча не доезжало бы
        # до кадра — та же тихая потеря, только с другого конца.
        kwargs.update(слайд.родное)
        kwargs.update(ЗАКРЕПЛЁННЫЕ.get(self.имя, {}))
        return kwargs

    def нарисовать(self, слайд: Слайд, выход=None, опустить=()):
        """Позвать движок общей формой. Вернуть Path (вид «файл») или PIL."""
        self.проверить(слайд, выход, опустить)
        итог = self._функция(**self.аргументы(слайд, выход))
        if self.возможности.вид == "образ":
            return итог[0] if isinstance(итог, tuple) else итог
        путь = Path(выход)
        if not путь.exists():
            raise ОтказПереходника(
                f"{self.имя}.{self.возможности.вход}: файл {путь.name} не "
                f"создан — движок отработал, но кадра нет")
        return путь


def _значение_понятия(имя_параметра: str, понятие: str, слайд: Слайд):
    """Значение общей формы под конкретный параметр движка."""
    if понятие == СЧЁТЧИК:
        return слайд.номер if имя_параметра == "i" else слайд.всего
    if понятие == ЗАГОЛОВОК:
        return слайд.заголовок
    if понятие == ПОДЗАГОЛОВОК:
        return слайд.подзаголовок
    if понятие == КАРТИНКА:
        return слайд.картинка
    if понятие == АКЦЕНТ:
        return tuple(слайд.акцент)
    if понятие == КАДРЫ:
        return list(слайд.кадры)
    raise AssertionError(f"неизвестное понятие: {понятие}")   # pragma: no cover


def _обязателен(fn, имя: str) -> bool:
    п = inspect.signature(fn).parameters[имя]
    return п.default is inspect.Parameter.empty


