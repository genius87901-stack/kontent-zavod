# -*- coding: utf-8 -*-
"""
ОБЩАЯ ФОРМА ВЫЗОВА ДВИЖКОВ — переходник между «одним слайдом» и 21 движком.

ЗАЧЕМ. У движков рендера общей формы вызова НЕТ, и это не впечатление, а счёт
(см. docs/ФАЗА2_СИГНАТУРЫ_ДВИЖКОВ.md): `cover` есть у 16 движков и имеет 15
разных форм; у одного нет подзаголовка, у другого на его месте счётчик, у
третьего выходной параметр зовётся `dest`, у четвёртого `i`/`n` обязательные.
Поэтому сборщик привязан к одному стилю, а каждый выпуск пишется отдельной
программой (123 файла `build_*.py`).

ЧТО ЗДЕСЬ. Одна форма входа (`Слайд`) и переходник на каждый движок, который
раскладывает её в РОДНЫЕ аргументы этого движка. Движки не меняются вообще:
переходник читает их ЖИВЫЕ сигнатуры через `inspect` и подставляет значения по
именам параметров. Ни один engine*.py этим модулем не правится и не
патчится.

ГЛАВНОЕ ПРАВИЛО — НИЧЕГО НЕ ТЕРЯТЬ МОЛЧА. Если движок не умеет подзаголовок,
переходник не выбрасывает текст, а ОТКАЗЫВАЕТСЯ по-русски
(`ОтказПереходника`). Молча потерянный текст хуже отказа: по отказу сборщик
возьмёт другой движок, а по тихой потере выпустят карусель без половины
смысла — и заметят это уже в ленте. Сознательно выбросить понятие можно, но
только вслух: `нарисовать(..., опустить={"подзаголовок"})`.

ПОНЯТИЯ ОБЩЕЙ ФОРМЫ (шесть, больше в сигнатурах движков не встречается):
    заголовок      — главный текст кадра;
    подзаголовок   — второй текстовый ряд, поясняющий заголовок;
    счётчик        — номер слайда и сколько всего;
    картинка       — ключ кадра в банке (engine4.PHOTOS);
    акцент         — цвет из палитры завода (engine4.ACCENTS), «стиль»;
    кадры          — готовые кадры ролика для видеослоёв (Reels).
Размер кадра — СЕДЬМОЕ понятие, но оно НЕ вход, а свойство движка: 1080x1350
у карусели, 1080x1920 у Reels. Поэтому размер не передаётся, а ОБЪЯВЛЯЕТСЯ
переходником (`Возможности.размер`) — сборщик узнаёт его до вызова.

СПИСОК ДВИЖКОВ СОБИРАЕТСЯ ИЗ КОДА. `движки()` — это `engine*.py` с диска, а
не переписанный руками перечень: новый движок попадает в реестр сам, и если
он не укладывается в общую форму, это видно сразу (`несведённые()`), а не
через полгода на сборке.

ИСПОЛЬЗОВАНИЕ:
    from engine_adapter import Слайд, нарисовать, возможности

    слайд = Слайд(заголовок="Как собрать карусель за вечер",
                  подзаголовок="без дизайнера и без Фигмы",
                  картинка="podcast_red", номер=1, всего=6)
    if "подзаголовок" in возможности("engine_photo").умеет:
        нарисовать("engine_photo", слайд, "out/01.png")
"""
