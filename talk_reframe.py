# -*- coding: utf-8 -*-
"""W1: СГЛАЖИВАНИЕ ТРЕКА ЛИЦА ВО ВРЕМЕНИ — против дрожания кадра.

Болезнь. `engine_talk._cover_face` / `_cover_keep_head` / `_speaker_crop`
зовут mediapipe НА КАЖДОМ КАДРЕ и кладут сырую рамку прямо в позицию кропа.
Сглаживания во времени не было вообще, поэтому:
  • рамка детектора гуляет на несколько пикселей от кадра к кадру — это
    дрожание уходит один в один в позицию окна кадрирования;
  • одна пропущенная детекция = кадр прыгнул к центру и вернулся (щелчок).

Лекарство (донор: mehbul/chopify, MIT, функция `smooth_track` из
`render_clips.py` — см. THIRD_PARTY.md). Там алгоритм пакетный: весь трек
известен заранее. У нас движок стримит кадры, поэтому здесь ОНЛАЙН-версия того
же фильтра — он и так причинный (только прошлое), пакетным его делал лишь
подсчёт медианы для заполнения пропусков:

  1. ЭКСПОНЕНЦИАЛЬНОЕ сглаживание позиции: c += alpha*(face - c), alpha=0.20.
     Микродрожание детектора (единицы пикселей) гасится, реальный переезд
     головы отрабатывается за ~10 кадров.
  2. SNAP-ON-CUT: скачок центра больше JUMP_FRAC (22%) размера кадра — это не
     движение головы, это СКЛЕЙКА. Такой скачок делается мгновенным телепортом
     (c = face), а не плавным переездом через полкадра.
  3. ПОВОДОК (deadzone): сглаженный центр не отпускается от настоящего лица
     дальше, чем на (0.5 - MARGIN_FRAC) ширины окна — лицо не подпускается к
     краю окна ближе 18%. Это ограничитель отставания фильтра: EMA не «теряет»
     лицо на быстром движении.
  4. ЗАПОЛНЕНИЕ ПРОПУСКОВ последним известным центром. Донор заполняет весь
     трек, база — медиана известных. У нас медианы будущего нет и быть не
     может, поэтому: пропуск до GAP_HOLD кадров подряд — держим последний
     известный центр (лечит щелчок от одной потерянной детекции); дольше —
     состояние сбрасывается и вызывающий возвращается на СВОЙ прежний путь
     (центр-кроп) байт в байт. Долгая потеря лица — это уже не пропуск, это
     b-roll или отвернувшийся спикер.

Состояние держится по КЛЮЧУ вызова (`split_top`, `cmp_bot`, `speaker`, ...):
у каждого места вызова своё окно, свой исходник и свой трек.

W2 добавляет сюда `Tracker` — РАЗРЕЖЕННУЮ детекцию (F1) и СБРОС НА СТЫКЕ (F4).
Доноры: тот же `mehbul/chopify` (MIT, `render_clips.py::detect_track` — константы
DET_FPS=5 и DET_W=640) и `AhmedHisham1/pyautoflip` (MIT, Copyright (c) 2024 Ahmed
Hisham, `scene_cropper.py` — путь камеры считается посценно). См. THIRD_PARTY.md
и докстринг класса.

Зависимостей нет (стандартная библиотека). Ничего не качает, ничего не пишет.
"""

EMA_ALPHA = 0.20        # донор: сила экспоненциального сглаживания
JUMP_FRAC = 0.22        # донор: скачок больше 22% кадра = склейка → телепорт
MARGIN_FRAC = 0.18      # донор: лицо не ближе 18% окна к его краю (поводок)
GAP_HOLD = 15           # наше: сколько кадров держать лицо при пропуске (~0.5 с)
CLICK_PX = 8.0          # наше: межкадровый скачок кропа выше этого — «щелчок»


class Smoother:
    """Онлайн-сглаживатель трека лица. Один экземпляр на рендер ролика.

    Дефолтные константы — донорские. Метод `center` сглаживает точку (центр
    лица), `box` — рамку (центр + размер). Оба принимают СЫРОЙ результат
    детектора или None и возвращают сглаженное значение или None (None ⇒
    вызывающий идёт своим прежним путём без лица).
    """

    def __init__(self, alpha=EMA_ALPHA, jump_frac=JUMP_FRAC,
                 margin_frac=MARGIN_FRAC, hold=GAP_HOLD, click_px=CLICK_PX):
        self.alpha = float(alpha)
        self.jump_frac = float(jump_frac)
        self.margin_frac = float(margin_frac)
        self.hold = int(hold)
        self.click_px = float(click_px)
        self._st = {}          # key -> состояние фильтра
        self._trk = {}         # key -> {"raw": [(x,y)...], "sm": [(x,y)...]}

    # ---------- фильтр ----------

    def reset(self, key=None):
        """Сбросить состояние (все ключи или один). Трассы замера не трогаем."""
        if key is None:
            self._st.clear()
        else:
            self._st.pop(key, None)

    def _fill(self, key, pt):
        """Заполнение пропусков. pt — сырой центр или None. → центр или None."""
        st = self._st.get(key)
        if pt is not None:
            if st is None:
                st = self._st[key] = {}
            st["miss"] = 0
            st["raw"] = (float(pt[0]), float(pt[1]))
            return st["raw"]
        if st is None or "raw" not in st:
            return None                     # лица ещё не было — прежний путь
        st["miss"] = st.get("miss", 0) + 1
        if st["miss"] > self.hold:
            self._st.pop(key, None)         # долгая потеря — не пропуск, а «нет лица»
            return None
        return st["raw"]                    # держим последний известный центр

    def center(self, key, pt, span, win):
        """Сгладить центр лица.

        pt   — (x, y) сырой детекции в пикселях ИСХОДНИКА или None;
        span — (W, H) исходника (порог склейки — доля от него);
        win  — (ww, wh) окно кадрирования, пересчитанное в пиксели ИСХОДНИКА
               (поводок — доля от него).
        Возвращает сглаженный (x, y) или None.
        """
        face = self._fill(key, pt)
        if face is None:
            return None
        st = self._st[key]
        prev = st.get("prev")
        cur = st.get("c")
        if cur is None or prev is None:
            st["c"] = list(face)                       # первый кадр — как есть
            st["_cut"] = True                          # для `box`: размер тоже как есть
        else:
            cut = any(abs(face[i] - prev[i]) > span[i] * self.jump_frac
                      for i in (0, 1))
            st["_cut"] = cut
            for i in (0, 1):
                if cut:
                    cur[i] = face[i]                   # СКЛЕЙКА — телепорт
                else:
                    cur[i] += self.alpha * (face[i] - cur[i])
                # поводок: лицо не ближе margin_frac окна к краю окна
                off = max(1.0, win[i] * (0.5 - self.margin_frac))
                if face[i] - cur[i] > off:
                    cur[i] = face[i] - off
                elif cur[i] - face[i] > off:
                    cur[i] = face[i] + off
            st["c"] = cur
        st["prev"] = list(face)
        return (st["c"][0], st["c"][1])

    def box(self, key, bx, span, win):
        """Сгладить рамку лица (x0,y0,x1,y1). Центр — тем же фильтром, что и
        `center`; РАЗМЕР рамки — та же экспонента (без поводка: размер не
        «убегает», а его дрожание раскачивает зум `_cover_keep_head`). Склейка
        телепортирует и центр, и размер. Возвращает рамку или None."""
        pt = None if bx is None else ((bx[0] + bx[2]) / 2.0,
                                      (bx[1] + bx[3]) / 2.0)
        # размер кладём в состояние ДО center(): center() решает про склейку и
        # может сбросить ключ, поэтому размер обновляем после него.
        c = self.center(key, pt, span, win)
        if c is None:
            return None
        st = self._st[key]
        if bx is not None:
            st["rawsz"] = (abs(bx[2] - bx[0]), abs(bx[3] - bx[1]))
        sz = st.get("rawsz")
        if sz is None:
            return None
        s = st.get("sz")
        if s is None or st.get("_cut"):
            s = list(sz)
        else:
            for i in (0, 1):
                s[i] += self.alpha * (sz[i] - s[i])
        st["sz"] = s
        return (c[0] - s[0] / 2.0, c[1] - s[1] / 2.0,
                c[0] + s[0] / 2.0, c[1] + s[1] / 2.0)

    # ---------- замер (само-baseline: сырой и сглаженный кроп в одном рендере) ----------

    def note(self, key, raw_xy, sm_xy):
        """Записать позицию окна кадрирования этого кадра: какой она была БЫ на
        сырой детекции и какая вышла на сглаженной. Обе считает вызывающий, в
        одном и том же рендере — сравнение честное, без дрейфа энкода."""
        t = self._trk.setdefault(key, {"raw": [], "sm": []})
        t["raw"].append((float(raw_xy[0]), float(raw_xy[1])))
        t["sm"].append((float(sm_xy[0]), float(sm_xy[1])))

    def _series(self, pts):
        """Метрики дрожания одной последовательности позиций кропа."""
        n = len(pts)
        if n < 2:
            return None
        d = []
        for i in range(1, n):
            dx = pts[i][0] - pts[i - 1][0]
            dy = pts[i][1] - pts[i - 1][1]
            d.append((dx * dx + dy * dy) ** 0.5)
        d_sorted = sorted(d)
        mean = sum(d) / len(d)
        var = sum((v - mean) ** 2 for v in d) / len(d)
        p95 = d_sorted[min(len(d) - 1, int(round(0.95 * (len(d) - 1))))]
        return {
            "frames": n,
            "d_mean_px": round(mean, 3),         # средний межкадровый сдвиг
            "d_var_px2": round(var, 3),          # покадровая дисперсия
            "d_p95_px": round(p95, 2),
            "d_max_px": round(max(d), 2),        # максимальный скачок
            "clicks": int(sum(1 for v in d if v > self.click_px)),
        }

    def report(self):
        """Сводка «до/после» по всем местам вызова. {} — замеров не было."""
        out = {}
        for key, t in self._trk.items():
            before = self._series(t["raw"])
            after = self._series(t["sm"])
            if before is None or after is None:
                continue
            out[key] = {"before": before, "after": after}
        return out


# ===================== W2: разреженная детекция (F1) + стык (F4) =============

DET_FPS = 5.0           # донор chopify: DET_FPS=5 — частота сэмплов детектора
DET_MAX_W = 640         # донор chopify: DET_W=640 — ширина кадра для детекции
DET_MIN_GAIN = 1.5      # наше: ужимать, только если ширина больше max_w в 1.5 раза


def det_stride(fps, sample_fps=DET_FPS):
    """Шаг сэмплирования детектора В КАДРАХ при частоте ролика fps.

    Донор гонит отдельный низкорезный проход на 5 fps; у нас отдельного прохода
    нет (движок и так читает каждый кадр), поэтому те же 5 сэмплов в секунду
    выражаются шагом по номеру кадра: 30 fps → каждый 6-й кадр.
    """
    try:
        f = float(fps)
    except (TypeError, ValueError):
        return 1
    if f <= 0 or f != f:                       # 0 или NaN
        return 1
    return max(1, int(round(f / float(sample_fps))))


class Tracker:
    """F1 + F4: сколько раз и на какой картинке звать детектор лица.

    ЗАЧЕМ. `engine_talk` звал mediapipe НА КАЖДОМ КАДРЕ ПОЛНОГО РАЗРЕШЕНИЯ, в
    каждом месте кадрирования отдельно. Это главный расход времени рендера на
    машине без видеокарты. Донор (`mehbul/chopify`, MIT, `render_clips.py`) делает
    иначе: ОТДЕЛЬНЫЙ проход детектора на `DET_FPS=5` кадрах в секунду и ширине
    `DET_W=640`, трек в память, а промежутки между сэмплами закрывает тот же
    экспоненциальный фильтр `smooth_track`, что уже лежит выше в этом файле.

    ЧТО ЗДЕСЬ. Два независимых сокращения, оба донорские:
      • РАЗРЕШЕНИЕ: кадр перед детекцией ужимается до `max_w` (640). mediapipe
        отдаёт ОТНОСИТЕЛЬНЫЕ координаты рамки, поэтому единицы результата не
        меняются — вызывающий по-прежнему умножает их на размер ИСХОДНИКА.
      • ЧАСТОТА: детектор зовётся не чаще раза в `stride` кадров на КЛЮЧ (у
        каждого места кадрирования свой источник и свой трек). Между сэмплами
        отдаётся последняя рамка, а сглаживание в неё «доезжает» экспонентой —
        это и есть интерполяция донора, только онлайновая.

    ПОЧЕМУ НЕ ОТДЕЛЬНЫМ ПРОХОДОМ, как у донора. Отдельный проход — это второй
    декод файла; у нас движок и так держит кадр в руках, поэтому дешевле
    сэмплировать прямо в цикле рендера. Плюс кадрируются РАЗНЫЕ источники
    (спикер, второй клип compare, каждая вставка b-roll), и отдельный проход
    пришлось бы делать по каждому.

    ПОЧЕМУ НЕ `face_track` ИЗ `source_meta.json`. Он есть, но не годится:
      1. шаг 0.5 с = 2 сэмпла в секунду — вчетверо грубее донорских 5 fps;
         на зум-ударе (punch) и в split голова успевает уехать за полсекунды;
      2. он снят с ИСХОДНОГО файла, а движок рендерит тот файл, что ему дали
         (после `talk_tighten` это уже другая нарезка) — соответствие времён
         не гарантировано ничем;
      3. он есть только для спикера: у второго клипа compare и у клипов b-roll
         своего трека в meta нет, а кадрируются они тем же `_cover_keep_head`.
    Поэтому свой шаг и свой сэмплинг по месту вызова. Обоснование — в журнале.

    F4 — СБРОС НА СТЫКЕ. `cut()` выбрасывает все запомненные рамки: на монтажной
    границе (в split спикер и перебивка меняются местами, а b-roll — вообще
    новый клип) старый трек не должен «переезжать» в новую сцену. Идея — из
    `AhmedHisham1/pyautoflip` (MIT), где путь камеры считается ПОСЦЕННО:
    `SceneCropper.process_scene` вызывается на сцену, состояние между сценами
    не переносится.

    Класс ничего не импортирует и ничего не знает про mediapipe: детекцию делает
    замыкание `detect`, переданное в `sample`.
    """

    def __init__(self, stride=6, max_w=DET_MAX_W, min_gain=DET_MIN_GAIN):
        self.stride = max(1, int(stride))
        self.max_w = int(max_w)
        self.min_gain = float(min_gain)
        self.fi = 0
        self._s = {}           # key -> (номер кадра сэмпла, рамка или None)
        self.calls = 0         # сколько раз реально звали детектор
        self.asks = 0          # сколько раз рамка вообще потребовалась
        self.cuts = 0          # сколько раз сбрасывались на стыке

    def tick(self, fi):
        """Отметить номер текущего кадра рендера (зовётся раз на кадр)."""
        self.fi = int(fi)

    def cut(self):
        """F4: монтажный стык — забыть трек, следующий кадр сэмплируется заново."""
        self._s.clear()
        self.cuts += 1

    def scale(self, w):
        """Во сколько ужать кадр шириной w перед детекцией (1.0 — не жать).

        ЗАМЕРЕНО (M1, кадр 720×1280, 80 кадров): сам `cv2.resize` стоит 2.70 мс
        (INTER_AREA) против 4.37 мс на всю полнокадровую детекцию. То есть при
        мелком ужатии даунскейл не окупается — он ДОРОЖЕ того, что экономит.
        Поэтому жмём, только когда площадь падает минимум в min_gain² ≈ 2.25 раза
        (ширина больше max_w в 1.5 раза). 1080p и 4k под порог попадают, 720p —
        нет, и там детекция идёт полным кадром, как раньше.
        """
        if self.max_w <= 0 or w <= self.max_w * self.min_gain:
            return 1.0
        return float(self.max_w) / float(w)

    def sample(self, key, detect):
        """Рамка лица для места `key`: свежая (сэмпл) или последняя известная.

        detect() — замыкание, делающее настоящий вызов детектора. Зовётся ТОЛЬКО
        на сэмплах. Возврат detect() кладётся в трек как есть, включая None
        («лица нет») — пропуск тоже держится до следующего сэмпла, а дальше его
        разбирает `Smoother` (у него свой лимит удержания GAP_HOLD).
        """
        self.asks += 1
        st = self._s.get(key)
        if st is not None and 0 <= self.fi - st[0] < self.stride:
            return st[1]
        b = detect()
        self.calls += 1
        self._s[key] = (self.fi, b)
        return b

    def report(self):
        """Сводка для meta: сколько вызовов детектора сэкономлено."""
        return {
            "stride": self.stride,
            "sample_fps": round(DET_FPS, 2),
            "max_w": self.max_w,
            "min_gain": self.min_gain,     # порог, ниже которого не ужимаем
            "det_calls": self.calls,       # реальных вызовов mediapipe
            "det_asks": self.asks,         # вызовов было БЫ при покадровой
            "det_saved": (round(1.0 - self.calls / float(self.asks), 3)
                          if self.asks else None),
            "cuts": self.cuts,             # сбросов на монтажных стыках (F4)
        }
