# Поэтому смотрим на кривую источника и трогаем только HDR.
TONEMAP = ("zscale=t=linear:npl=100,format=gbrpf32le,zscale=p=bt709,"
           "tonemap=mobius:desat=0,zscale=t=bt709:m=bt709:r=tv,format=yuv420p")

_HDR_TRC = ("arib-std-b67", "smpte2084")     # HLG и PQ (Dolby Vision)
_hdr_cache = {}


def is_hdr(path):
    """Записан ли клип в HDR. ffprobe в imageio-ffmpeg нет — читаем stderr
    `ffmpeg -i` (он на отсутствие выхода отдаёт код 1, это норма, не ошибка)."""
    key = os.path.abspath(path)
    if key not in _hdr_cache:
        r = subprocess.run([FF, "-hide_banner", "-i", path],
                           capture_output=True, text=True, errors="replace")
        line = next((l for l in (r.stderr or "").splitlines() if "Video:" in l), "")
        _hdr_cache[key] = any(t in line for t in _HDR_TRC)
    return _hdr_cache[key]


def vf_for(path):
    """Цепочка приведения кадра для ЭТОГО клипа. Одна на весь модуль: кадры для
    анализа и финальный рендер обязаны видеть одну и ту же картинку, иначе замер
    фона под текстом делается по одному изображению, а текст ложится на другое."""
    return VF_916 + ("," + TONEMAP if is_hdr(path) else "")


def auto_start(total, want):
    """С какой секунды брать кусок, если сборка не назвала момент сама.

    23.08.2026, просьба Валерии: «если видео длинное — начинай с 7-8 секунды,
    чтобы не было видно, как я поправляюсь». Первые секунды съёмки с руки или
    со штатива — это установка кадра: она поправляет волосы, платье, ищет
    ракурс. Материал есть, но в ленте он выглядит как случайно начатая запись.

    Голову срезаем ТОЛЬКО когда клип это переживёт: после пропуска должен
    остаться кусок полной желаемой длины. Иначе ролик станет короче — а
    короткий Reels хуже некрасивого начала, и MIN_SEC уже стоит на страже.
    Короткий клип, снятый сразу «в кадр», обычно и не нуждается в пропуске.
    """
    return SKIP_HEAD if total - SKIP_HEAD >= want else 0.0


def probe(path):
    """Длительность/размер. ffprobe в imageio-ffmpeg НЕ входит, поэтому cv2."""
    import cv2
    c = cv2.VideoCapture(path)
    fps = c.get(cv2.CAP_PROP_FPS) or 0
    n = c.get(cv2.CAP_PROP_FRAME_COUNT) or 0
    w = int(c.get(cv2.CAP_PROP_FRAME_WIDTH))
    h = int(c.get(cv2.CAP_PROP_FRAME_HEIGHT))
    c.release()
    return (n / fps if fps else 0.0), w, h


