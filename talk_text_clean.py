# -*- coding: utf-8 -*-
"""Детерминированная чистка распознанного текста (стадия 2, после WhisperX).

ЗАЧЕМ. Текст распознавания уходит в субтитры КАК ЕСТЬ, а субтитр вжигается в
картинку — любой огрех остаётся в опубликованном ролике навсегда. Здесь мы
чиним то, что чинится ПРАВИЛАМИ, без обращения к модели: пунктуация, регистр,
пробелы. Семантику («не то слово распозналось», «е вместо ё») правилами не
починить — это отдельная задача и отдельное решение владельца о ключе.

ЖЁСТКОЕ ОГРАНИЧЕНИЕ — ТАЙМИНГИ. У каждого слова свои `s`/`e`, по ним ездит
караоке-подсветка (engine_talk.chunk_cues_karaoke). Поэтому чистка правит
ТОЛЬКО строку `w` внутри слова. Число слов не меняется, порядок не меняется,
`s`/`e`/`sc` копируются как есть. Любое правило, которому нужно СКЛЕИТЬ или
УДАЛИТЬ слово, здесь НЕ применяется — см. `diagnose()` и разбор ниже.

ЧТО ПОКАЗАЛ ЗАМЕР на живых транскриптах (out_talk/*_transcript*.json,
151 и 152 слова, один и тот же спикер, два прогона WhisperX):

    небуквенные символы во всём корпусе:  «,» «.» «-» и цифры. И ВСЁ.
    токенов с пробелом внутри/по краям:   0   (_to_engine_format уже strip-ает)
    токенов, начинающихся с пунктуации:   0   (знак всегда приклеен к слову)
    многоточий («...» или «…»):           0
    соседних одинаковых слов («и и»):     0
    токенов без букв и цифр (мусор):      0
    двойной пунктуации («,,», «..»):      0
    кавычек, латиницы, NBSP:              0
    дефисов:                              3 и 5 — ВСЕ внутри слова
                                          (мы-то, какие-то, что-то) — законные
    одиночных букв:                       12 и 11 — ВСЕ законные русские слова
                                          (и, а, о, в, к, я) — не мусор
    строчная в начале предложения:        1 и 1  ← ЕДИНСТВЕННЫЙ реальный дефект

Единственный дефект, который видно на экране: реплика «других клиентов,» идёт
сразу за «просто другой мир.» — новое предложение с маленькой буквы. Его и
чиним правилом REGISTR ниже.

ПОЧЕМУ ПОЛОВИНА СПИСКА ИЗ ЗАДАНИЯ ЗДЕСЬ НЕ РЕАЛИЗОВАНА. Не потому, что лень, а
потому, что в этом пайплайне она либо недостижима, либо ломает тайминги:

* «пробел перед запятой», «нет пробела после», «двойные пробелы», «пробелы в
  конце реплики» — НЕДОСТИЖИМЫ ПО УСТРОЙСТВУ. Реплика собирается как
  `" ".join(слова)` (engine_talk._phrase_to_cues), знак препинания приклеен к
  слову, а `_to_engine_format` уже сделал strip. Лишний пробел взяться неоткуда.
  Единственная форма, в которой беда МОГЛА БЫ появиться — отдельный токен-знак
  («,» своим словом). Чинится он только СКЛЕЙКОЙ с предыдущим словом, а это
  минус одно слово и сдвиг подсветки → запрещено. Мы такой токен НЕ чиним, а
  считаем в `diagnose()`.
* «повторы-склейки (и и, в в)» — чинятся только УДАЛЕНИЕМ слова → запрещено
  таймингами. В корпусе их и нет ни одного. Считаем в `diagnose()`.
* «висящие одиночные буквы» — в корпусе таких нет: все одиночные буквы это
  и/а/о/в/к/я, законные русские слова. Удаление опять же меняло бы число слов.
* «дефис вместо тире в прямой речи» — отдельного токена-дефиса в корпусе нет
  (0 штук), а превращать его в «—» ОПАСНО: «—» входит в engine_talk._PUNCT, то
  есть разрывает фразу на реплики, и тире осталось бы на экране одно, отдельной
  репликой. Диапазоны (цифра-дефис-цифра) — другое дело, там разрыва не будет,
  это правило есть. Дефис ВНУТРИ слова (какие-то) не трогаем никогда.

ЧТО ПРАВИЛА НЕ ПОЧИНЯТ В ПРИНЦИПЕ (нужна модель): выбор слова («твердые»
вместо «твёрдые» — в одном прогоне «начнёшь/ещё», в другом «начнешь/еще», и
какой верен, решает словарь, а не правило), согласование, пропущенные знаки,
неверно распознанные термины и имена.
"""
from __future__ import annotations

import re

#: Знаки, после которых начинается новое предложение.
_SENT_END = ".!?…"

#: Токен-инициал/сокращение вида «т.» «г.» «И.» — точка в нём НЕ конец
#: предложения, иначе следующее слово получило бы ложную заглавную.
_INITIAL = re.compile(r"^[^\W\d_]\.$", re.UNICODE)

#: Первая буква, которую можно поднять в верхний регистр (пропускаем открывающие
#: кавычки/скобки/тире, если они вдруг приклеились к началу токена).
_FIRST_CASED = re.compile(r"[^\W\d_]", re.UNICODE)

#: Диапазон цифрами через дефис: 20-30 → 20–30 (короткое тире).
_RANGE = re.compile(r"(?<=\d)-(?=\d)")

#: Три и более точки подряд → символ многоточия.
_DOTS = re.compile(r"\.{3,}")

#: Повтор одного и того же знака препинания: «,,» «!!» «::» → один знак.
#: Точку сюда НЕ включаем: её многоточие уже разобрало, а «..» ниже сведётся
#: тем же правилом только после того, как _DOTS отработал.
_DOUBLED = re.compile(r"([,;:!?.…])\1+")

#: Любой пробельный разбег внутри токена.
_SPACES = re.compile(r"\s+")


def clean_token(tok: str) -> str:
    """Почистить ОДНО слово правилами, не зависящими от соседей.

    Возвращает строку той же роли: одно слово. Ни склейки, ни разрыва —
    вызывающий код кладёт результат обратно в то же слово с теми же `s`/`e`.

    Пустую строку не возвращаем никогда: пустое слово engine_talk.chunk_cues
    молча пропускает (`if not word: continue`), а это минус слово в караоке —
    ровно то, что нам запрещено. Если чистка съела токен целиком, отдаём
    исходный.
    """
    if not tok:
        return tok
    out = _SPACES.sub(" ", tok).strip()
    # Порядок важен: сначала «...» → «…», иначе _DOUBLED свёл бы три точки в
    # одну и многоточие потерялось бы совсем.
    out = _DOTS.sub("…", out)
    out = _DOUBLED.sub(r"\1", out)
    out = _RANGE.sub("–", out)
    return out or tok


def _ends_sentence(tok: str) -> bool:
    """Слово закрывает предложение? Инициал «т.» — не закрывает."""
    if not tok or tok[-1] not in _SENT_END:
        return False
    return not _INITIAL.match(tok)


def _capitalize_first(tok: str) -> str:
    """Поднять первую БУКВУ токена, не трогая остальные.

    Именно первую букву, а не `tok.capitalize()`: тот опустил бы хвост и
    «мы-то» стало бы «Мы-то» правильно, а «ИП» — «Ип» неправильно.
    Токен без единой буквы возвращается как есть.
    """
    m = _FIRST_CASED.search(tok)
    if not m:
        return tok
    i = m.start()
    return tok[:i] + tok[i].upper() + tok[i + 1:]


def clean_words(words):
    """Плоский поток слов [{w,s,e,...}] → новый список с почищенными `w`.

    Число слов, их порядок и все поля кроме `w` сохраняются один в один —
    это и есть гарантия неприкосновенности таймингов.

    Регистр считается по ЗНАКАМ ПРЕПИНАНИЯ сквозь весь поток, а не по границам
    сегментов WhisperX: сегмент — это кусок звука, а не предложение. Живой
    пример: сегмент «других клиентов, да, …» идёт после «…другой мир.» —
    предложение новое, буква должна быть заглавная, хотя WhisperX её не поднял.
    Обратный случай («И ты притягиваешь…» после запятой) мы НЕ опускаем: это
    может быть имя собственное, а отличить имя от союза — работа модели, не
    правила.
    """
    out = []
    at_start = True                     # ждём первое слово предложения
    for w in words:
        item = dict(w)
        tok = clean_token(str(item.get("w", "")))
        if at_start:
            if _FIRST_CASED.search(tok):
                tok = _capitalize_first(tok)
                at_start = False
            elif re.search(r"\w", tok, re.UNICODE):
                # Слово без буквы, но со знаком-словом (число: «20 лет») —
                # место начала предложения занято, следующее слово поднимать
                # уже НЕЛЬЗЯ, иначе выйдет «20 Лет».
                at_start = False
            # Иначе токен — чистая пунктуация, начало предложения ещё впереди.
        if _ends_sentence(tok):
            at_start = True
        item["w"] = tok
        out.append(item)
    return out


def clean_transcript(segments):
    """Транскрипт стадии 2 → он же с почищенным текстом.

    Вход/выход — формат завода: СПИСОК сегментов `{"end": float, "words": [...]}`
    (см. talk_transcribe). Сегменты, их `end` и число слов в каждом остаются
    прежними; меняются только строки `w`.

    Регистр считается сквозь весь транскрипт, поэтому слова сначала
    раскладываются в один поток, а потом разбираются обратно по исходным длинам
    сегментов — так граница сегмента не сбивает счёт предложений.
    """
    segs = list(segments or [])
    flat = [w for seg in segs for w in seg.get("words", [])]
    cleaned = clean_words(flat)

    out, pos = [], 0
    for seg in segs:
        n = len(seg.get("words", []))
        item = dict(seg)
        item["words"] = cleaned[pos:pos + n]
        pos += n
        out.append(item)
    return out


def diagnose(segments):
    """Посчитать в транскрипте то, что мы СОЗНАТЕЛЬНО не чиним.

    Не правит ничего — это замерялка. Нужна, чтобы на новых транскриптах
    (другая модель, другой спикер, `--quality final`) владелец мог увидеть,
    появилось ли то, чего в замере не было, и стоит ли возвращаться к вопросу.

    Ключи (все — «требует склейки/удаления слова, таймингами запрещено»):
      punct_only   — отдельный токен-знак: даёт пробел перед запятой, чинится
                     только склейкой с предыдущим словом;
      doubled_word — соседние одинаковые слова («и и»): чинится удалением;
      no_word_char — токен без единой буквы и цифры (мусорная вставка).
    """
    flat = [w for seg in (segments or []) for w in seg.get("words", [])]
    toks = [str(w.get("w", "")) for w in flat]

    punct_only = sum(1 for t in toks if t and not re.search(r"\w", t, re.UNICODE)
                     and re.search(r"[^\w\s]", t, re.UNICODE))
    no_word_char = sum(1 for t in toks
                       if t and not re.search(r"\w", t, re.UNICODE))

    def bare(t):
        return re.sub(r"[^\w]", "", t, flags=re.UNICODE).lower()

    # ПОВТОР ПОВТОРУ РОЗНЬ. Считаем только СЛИПШИЙСЯ повтор — «и и», где между
    # словами нет ни одного знака. Замер 04.09.2026 на третьем живом ролике:
    # все три «повтора» оказались речью человека, а не браком распознавания —
    # «просто, просто», «Ничего. Ничего», «плохо? Плохо». Их разделяет знак,
    # поставленный самим WhisperX, и удалять их нельзя: это авторский приём.
    # Без этого условия замерялка звала владельца на здоровый текст.
    doubled = 0
    for i in range(len(toks) - 1):
        a, b = bare(toks[i]), bare(toks[i + 1])
        if a and a == b and not re.search(r"[^\w\s]", toks[i], re.UNICODE):
            doubled += 1

    return {"punct_only": punct_only,
            "doubled_word": doubled,
            "no_word_char": no_word_char}
