# ── ПОДСКАЗКИ ОПЕРАТОРУ (E4-29) ──────────────────────────────────────────────
# Гейт читает не программист, а человек, который собрал ролик и уткнулся в
# отказ. «Субтитр на лице» и «текст вне безопасной зоны» говорят ЧТО не так и
# молчат о том, ЧТО С ЭТИМ ДЕЛАТЬ, — дальше человек стоит перед стеной. Поэтому
# каждое сообщение гейта состоит из трёх частей: что случилось → насколько
# (число) → что сделать. Пороги и вердикты pass/fail при этом те же самые:
# правится ТОЛЬКО текст, ни одна проверка не ослаблена.
#
# Чтобы перевести пиксели в понятную человеку меру («укоротите примерно на N
# символов»), нужна средняя ширина символа. Замер 09.08.2026 на гарнитуре
# завода (Onest Bold, engine4.font, русские фразы): отношение средней ширины
# символа к кеглю — 0.545 / 0.546 / 0.539 / 0.534 / 0.537 на кеглях
# 34/50/74/100/222; разброс по разным фразам 0.52..0.57 (сплошной капс шире,
# 0.71, но капсом субтитры не набираются). Отсюда 0.55 и слово «примерно»:
# задача — дать порядок величины, по которому человек поймёт, резать одно
# слово или полфразы, а не типографская точность.
CHAR_W_K = 0.55
# Шаг строки к кеглю (замер там же, line_gap=1.12 как в _text_sprite_wrapped):
# 1.30 при кегле 74, 1.22 при 100, 1.11 при 222 — берём 1.2.
LINE_H_K = 1.2
# Кегль субтитра приходит в meta['sub_px']; старый рендер его не клал — тогда
# берём базу движка для split/×N (engine_talk.sub_size_for), чтобы подсказка
# всё равно называла число, пусть и грубее.
SUB_PX_FALLBACK = 74


def _plural(n, one, few, many):
    """«1 символ / 2 символа / 5 символов» — подсказку читает человек."""
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not (12 <= n % 100 <= 14):
        return few
    return many


def _approx_chars(px, sub_px=None):
    """px по горизонтали → сколько это примерно СИМВОЛОВ субтитра."""
    size = float(sub_px or SUB_PX_FALLBACK)
    return max(1, int(round(float(px) / max(1.0, size * CHAR_W_K))))


def _approx_lines(px, sub_px=None):
    """px по вертикали → сколько это примерно СТРОК субтитра."""
    size = float(sub_px or SUB_PX_FALLBACK)
    return max(1, int(round(float(px) / max(1.0, size * LINE_H_K))))


def _chars_hint(px, sub_px=None):
    """«примерно на 4 символа» — готовый кусок фразы."""
    n = _approx_chars(px, sub_px)
    return "примерно на %d %s" % (n, _plural(n, "символ", "символа", "символов"))


def _lines_hint(px, sub_px=None):
    """«примерно 2 строки» — готовый кусок фразы."""
    n = _approx_lines(px, sub_px)
    return "примерно %d %s" % (n, _plural(n, "строку", "строки", "строк"))


_RE_SIZE = re.compile(r"\b(\d{3,5})x(\d{3,5})\b")


def _out_size(info):
    """Фактическое разрешение готового файла из вывода `ffmpeg -i` → «1920x1080»
    или None. Нужно только для подсказки: «не 1080x1920» без второго числа не
    говорит человеку ничего."""
    for line in (info or "").splitlines():
        if "Video:" in line:
            m = _RE_SIZE.search(line)
            if m:
                return "%sx%s" % (m.group(1), m.group(2))
    return None


def _hue(rgb):
    r, g, b = [c / 255 for c in rgb]
    return colorsys.rgb_to_hsv(r, g, b)[0] * 360


def _hue_dist(a, b):
    d = abs(a - b) % 360
    return min(d, 360 - d)


# Допуск «цвет лежит на отрезке INK↔акцент». Смесь двух цветов даёт одинаковую
# долю t по всем трём каналам; чужой цвет — разную. Замер 08.08 на живых кадрах:
# сглаживание INK-буквы на плашке — разброс 0.003 и 0.014, чужой синий — 4.47,
# «вторая яркость акцента» (то, что правило и обязано ловить) — 0.47. Запас между
# ними тридцатикратный, поэтому 0.05 — с большим полем, а не впритык.
BLEND_TOL = 0.05
# Потолок доли акцента в смеси. Без него правило перестаёт ловить ОПЕЧАТКУ в
# литерале: (238,136,72) вместо orange (240,138,74) лежит на отрезке при t≈0.98 и
# проходил бы молча — а это ровно «вторая координата одного цвета», которую
# правило и создано ловить. Замер 08.08 по всем кадрам волны 2: крупная смесь во
# всём наборе ровно одна, t=0.260. Запас до потолка трёхкратный.
BLEND_MAX_T = 0.90


def _on_ink_blend(c, acc):
    """Цвет — это смесь INK и акцента (край буквы на плашке), а не чужая краска.

    ЗАЧЕМ. Правило «одному цвету одна координата» ловит сплошные пятна не-акцента.
    Но текст на плашке — тёмный INK поверх заливки, и его сглаженный контур даёт
    промежуточные оттенки. Пока плашек было мало, периметр не добирал до
    SOLID_MIN. После автокегля (волна 2) кегль вырос, периметр удлинился — и на
    раскладке checklist набежало 586 px оттенка (82,52,34) при акценте orange.
    Сборка падала на кадре, где дизайнерского нарушения нет вовсе: это граница
    между акцентом и INK, ровно то, что правило разрешает.
    """
    ts = []
    for i in range(3):
        d = float(acc[i]) - float(e.INK[i])
        if abs(d) < 1:          # канал не разделяет цвета — по нему не судим
            continue
        ts.append((float(c[i]) - float(e.INK[i])) / d)
    if not ts:
        return False
    # Смесь обязана лежать МЕЖДУ INK и акцентом, давать одинаковую долю по всем
    # каналам и не притворяться самим акцентом (см. BLEND_MAX_T).
    return (max(ts) - min(ts) <= BLEND_TOL) and (-BLEND_TOL <= min(ts)) \
        and (max(ts) <= BLEND_MAX_T)


# ── 1. ЕДИНСТВО ЦВЕТА ────────────────────────────────────────────────────────
def check_palette(png, acc):
    """Цвет на белом слайде — только акцент, только в его точном значении."""
    a = np.asarray(Image.open(png).convert("RGB")).astype(np.float32)
    mx = a.max(axis=2)
    mn = a.min(axis=2)
    v = mx / 255.0
    sat = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1), 0)
    mask = (v > V_MIN) & (sat > S_MIN)
    if not mask.any():
        return []

    # (а) сплошные пятна обязаны быть ровно акцентом
    out = []
    cols, cnt = np.unique(a[mask].astype(np.uint8).reshape(-1, 3),
                          axis=0, return_counts=True)
    for c, k in zip(cols, cnt):
        if (k >= SOLID_MIN and tuple(int(x) for x in c) != tuple(acc)
                and not _on_ink_blend(c, acc)):
            out.append("ВТОРОЙ ЦВЕТ НА СЛАЙДЕ %s: пятно %s площадью %d px — это "
                       "не акцент карусели %s. У карусели один акцент и ровно "
                       "одно его значение: акцент только заливкой, текст поверх "
                       "неё тёмный (см. engine_white, «ОДИН ЦВЕТ»). Что сделать: "
                       "если цвет задан в скрипте сборки числами — поставьте "
                       "вместо них акцент этой карусели; если это фотография — "
                       "слайд просто не объявлен, добавьте его номер в "
                       "photo_slides (кадр с человеком) или theme_slides "
                       "(кадр без человека) при вызове verify()."
                       % (png, tuple(int(x) for x in c), k, tuple(acc)))
    if out:
        return out

    # (б) тон — сеть на чужой цвет, размазанный тоньше порога площади
    px = a[mask] / 255.0
    r, g, b = px[:, 0], px[:, 1], px[:, 2]
    cmax = px.max(axis=1)
    cmin = px.min(axis=1)
    delta = np.maximum(cmax - cmin, 1e-6)
    h = np.zeros_like(cmax)
    i_r = (cmax == r)
    i_g = (cmax == g) & ~i_r
    i_b = (cmax == b) & ~i_r & ~i_g
    h[i_r] = 60 * (((g - b)[i_r] / delta[i_r]) % 6)
    h[i_g] = 60 * (((b - r)[i_g] / delta[i_g]) + 2)
    h[i_b] = 60 * (((r - g)[i_b] / delta[i_b]) + 4)

    target = _hue(acc)
    d = np.abs(h - target) % 360
    d = np.minimum(d, 360 - d)
    bad = d > HUE_TOL
    frac = bad.sum() / a.shape[0] / a.shape[1]
    if frac > BAD_FRAC:
        stray = h[bad]
        return ["ЧУЖОЙ ОТТЕНОК НА СЛАЙДЕ %s: %.2f%% пикселей не в тоне акцента "
                "(акцент — тон %.0f°, чужое — около %.0f°), порог %.2f%%. Так "
                "выглядит второй цвет, размазанный тонко: градиент, тень цветом, "
                "картинка-иконка. Что сделать: уберите со слайда всё цветное, "
                "кроме акцента, — либо, если это фотография, добавьте номер "
                "слайда в photo_slides/theme_slides при вызове verify()."
                % (png, frac * 100, target, float(np.median(stray)),
                   BAD_FRAC * 100)]
    return []


# ── 2. ТЕКСТ НА ЛИЦЕ ─────────────────────────────────────────────────────────
def face_boxes_img(img, conf=0.5):
    """Лица на ЛЮБОМ кадре (numpy RGB или PIL) → рамки в пикселях этого кадра.

    Вынесено из face_boxes, чтобы детектор был один на проект. Кадру видео
    e.fit() не подходит: у Reels своя геометрия (1080x1920), и кадр приходит
    не из банка фото, а из ffmpeg. Детектор при этом обязан остаться тем же —
    иначе «текст обходит лицо» в видео и в карусели means разные вещи.
    """
    a = np.asarray(img.convert("RGB")) if hasattr(img, "convert") else np.asarray(img)
    h, w = a.shape[:2]
    fd = mp.solutions.face_detection.FaceDetection(
        model_selection=1, min_detection_confidence=conf)
    res = fd.process(a)
    boxes = []
    for det in (res.detections or []):
        b = det.location_data.relative_bounding_box
        boxes.append((int(b.xmin * w), int(b.ymin * h),
                      int((b.xmin + b.width) * w),
                      int((b.ymin + b.height) * h)))
    return boxes


def face_boxes(photo_key, conf=0.5):
    """Лица на кадре в том виде, в каком его рендерит обложка (1080x1350)."""
    return face_boxes_img(e.fit(e.PHOTOS[photo_key], e.H), conf)


def check_face_safe(result, label="обложка"):
    """Текст ЭТОГО слайда не должен пересекать лицо — обобщение бывшей
    check_cover_face на любой слайд, не только обложку (E4-?? / стили-2026:
    жёсткий гейт лицо/текст нужен на каждом слайде, а не только на входе).

    Слайд без фото (result без ключа "photo" или photo=None) — большинство
    текстовых слайдов — тут проверять нечего, тихо пропускаем: это не «нет
    ошибки», это «вопрос не применим».
    """
    if not result or not result.get("photo"):
        return []
    if "text_bbox" not in result:
        return ["%s не вернула рамку текста (text_bbox), хотя фото на слайде "
                "есть — это поломка движка, а не вашего материала: обновите "
                "завод и соберите карусель заново" % label]
    tx0, ty0, tx1, ty1 = result["text_bbox"]
    boxes = face_boxes(result["photo"])
    if not boxes:
        return ["! лицо на слайде (%s) не распозналось автоматически — гляньте "
                "слайд глазами: не легли ли буквы на лицо" % label]
    out = []
    for (fx0, fy0, fx1, fy1) in boxes:
        ox = max(0, min(tx1, fx1) - max(tx0, fx0))
        oy = max(0, min(ty1, fy1) - max(ty0, fy0))
        if ox > 0 and oy > 0:
            area = (fx1 - fx0) * (fy1 - fy0)
            out.append(
                "ТЕКСТ НА ЛИЦЕ (%s): буквы закрывают %.0f%% лица. "
                "Что сделать — любое из трёх: (1) возьмите для этого слайда "
                "другое фото, где лицо выше или сбоку, а не по центру; "
                "(2) укоротите заголовок или подзаголовок — блок текста "
                "станет компактнее, и завод найдёт для него чистое место; "
                "(3) смените раскладку слайда на ту, где текст стоит в "
                "стороне (например cover_ref/cover_marker в скрипте сборки). "
                "Замер: лицо %s, текст %s (кадр 1080x1350)."
                % (label, ox * oy / area * 100, (fx0, fy0, fx1, fy1),
                   (tx0, ty0, tx1, ty1)))
    return out


def check_cover_face(cover_result):
    """Текст обложки не должен пересекать лицо.

    Оставлена как отдельная функция ради обратной совместимости внешнего
    вызова (сообщение об отсутствии text_bbox у обложки — особый случай,
    в check_face_safe для слайда без фото это не ошибка, а для обложки —
    всегда ошибка, у обложки фото обязано быть). Логика самого пересечения —
    в check_face_safe.
    """
    if not cover_result or "text_bbox" not in cover_result:
        return ["обложка не вернула рамку текста (text_bbox) — это поломка "
                "движка, а не вашего материала: обновите завод и соберите "
                "карусель заново"]
    return check_face_safe(cover_result, label="обложка")


# ── 2b. ТЕКСТ ЗА ПРЕДЕЛАМИ КАНВЫ ─────────────────────────────────────────────
def check_text_bounds(result, label, margin=None):
    """Рамка текста этого слайда обязана остаться внутри канвы с отступом от
    края со всех четырёх сторон. margin по умолчанию — engine4.M (72px), тот
    же отступ, что уже держат раскладки всех семейств.

    Слайд без text_bbox (большинство текстовых функций старых семейств до
    ретрофита) тут не проверяется — не «прошёл», а «недоступен для проверки»;
    как только функция начинает возвращать text_bbox, проверка включается
    сама, без правок в этом файле.
    """
    if not result or "text_bbox" not in result:
        return []
    m = e.M if margin is None else margin
    tx0, ty0, tx1, ty1 = result["text_bbox"]
    over = {
        "слева": max(0, m - tx0),
        "справа": max(0, tx1 - (e.W - m)),
        "сверху": max(0, m - ty0),
        "снизу": max(0, ty1 - (e.H - m)),
    }
    bad = {k: v for k, v in over.items() if v > 0}
    if not bad:
        return []
    parts = ["%s на %d px (%s)" % (
                k, v, _chars_hint(v) if k in ("слева", "справа") else _lines_hint(v))
             for k, v in bad.items()]
    return ["ТЕКСТ ВЫХОДИТ ЗА ПОЛЕ (%s): %s. Отступ от края канвы держим %d px "
            "везде. Что сделать: укоротите текст или уменьшите кегль — "
            "автоподбор возьмёт блок компактнее. "
            "Замер: рамка текста %s, канва %dx%d, безопасная зона по X "
            "%d..%d, по Y %d..%d."
            % (label, "; ".join(parts), m, (tx0, ty0, tx1, ty1), e.W, e.H,
               m, e.W - m, m, e.H - m)]


# ── 2c. ЗАВОД ДОНАСТРОЕН НЕ ДО КОНЦА (BOX-73) ────────────────────────────────
#
# ЗАЧЕМ ЭТО ЗДЕСЬ. Первая половина BOX-73 научила `updater` выполнять
# послеустановочные шаги и, если шаг НЕ прошёл, оставлять отметку
# `config/post_steps_pending.json`. Но читал эту отметку только
# `updater.py --status` — то есть завод продолжал работать в урезанном режиме
# МОЛЧА, ровно то, ради чего задача и заводилась: 1.3.44 потребовал ручного
# шага, никто о нём не узнал, и у ТРЁХ клиентов приём материалов с Google
# Диска умер — при том что это был их единственный работавший модуль
# («1 из 8» стало «0 из 8»), а обновление отчиталось успехом.
#
# ПОЧЕМУ ПРЕДУПРЕЖДЕНИЕ, А НЕ ОТКАЗ. У тех же троих сломанный приём был
# ЕДИНСТВЕННЫМ работавшим модулем. Уронить им ещё и сборку — отнять последнее.
# Задача проверки не «запретить», а «перестать делать вид, что всё в порядке»:
# строка идёт в общий список warnings и сборку не останавливает никогда.
#
# ПОЧЕМУ ИМПОРТ `updater`, А НЕ СВОЯ ЧИТАЛКА JSON. Дублировать путь и формат
# отметки нельзя: разойдутся молча — и получится ещё один «отказ, выглядящий
# как успех», уже в самой сигнализации. `updater` при этом дёшев и безопасен
# как импорт: у него в шапке только стандартная библиотека и НИ ОДНОЙ строки
# кода на уровне модуля (всё под `if __name__ == "__main__"`), так что импорт
# ничего не качает, не пишет и не печатает. Путь отметки, её формат и разбор
# берём у него же — POST_PENDING_FILE, pending_post_steps(), POST_STEPS.
# Человеческое название шага живёт в POST_STEPS: сама отметка хранит только
# идентификатор шага, причину и команду.


def post_setup_warnings(root=None):
    """Предупреждения «остался невыполненный шаг после обновления». Нет — [].

    Возвращает список строк в общем формате замечаний завода (начинаются с
    «!»). МОЛЧИТ И НЕ ПАДАЕТ ни при каком состоянии диска: отметки нет, файл
    битый, каталога `config/` нет, `updater` недоступен — везде пустой список.
    Проверка, которая сама стала источником отказов, хуже отсутствующей.
    """
    try:
        from pathlib import Path
        import updater                                       # noqa: WPS433
        base = Path(root) if root else Path(__file__).resolve().parent
        # pending_post_steps сам отдаёт {} на отсутствующем и битом файле
        # (updater._read_json глотает OSError и JSONDecodeError).
        data = updater.pending_post_steps(base)
        steps = data.get("steps") if isinstance(data, dict) else None
        if not isinstance(steps, list):
            return []
        version = str(data.get("version") or "").strip()
        known = getattr(updater, "POST_STEPS", {}) or {}
    except Exception:                                        # noqa: BLE001
        return []

    out = []
    for item in steps:
        if not isinstance(item, dict):
            continue
        name = str(item.get("step") or "").strip()
        why = str(item.get("why") or "").strip()
        manual = str(item.get("manual") or "").strip()
        spec = known.get(name) or {}
        title = str(spec.get("title") or "").strip() or name
        if not title:
            continue
        todo = ("Что сделать: откройте окно с чёрным экраном (терминал), где вы "
                "запускаете завод, и вставьте туда одну строку целиком, а "
                "вместо <папка Google Диска> подставьте свою папку:\n"
                "       %s" % manual) if manual else (
               "Что сделать: покажите эту строку разработчику — сама коробка "
               "этот шаг починить не умеет.")
        out.append(
            "! ЗАВОД ДОНАСТРОЕН НЕ ДО КОНЦА%s. После установки обновления "
            "осталось незаконченное дело: %s. Не получилось потому, что %s. "
            "Чем это грозит: эта часть завода работает НЕ ПОЛНОСТЬЮ и никак "
            "об этом не сообщает — ролики и карусели собираются как обычно, "
            "но всё, что зависит от незаконченного дела, будет тихо "
            "простаивать. Сборку из-за этого не останавливаю. %s\n"
            "     Когда дело будет сделано, эта строка пропадёт сама. Если "
            "команда не помогла — покажите разработчику файл %s."
            % (" (обновление %s)" % version if version else "", title,
               why or "причина не записана", todo, updater.POST_PENDING_FILE))
    return out


# ── 3. ПРОВЕРКА REELS ────────────────────────────────────────────────────────
def verify_reel(meta, strict=True):
    """Проверки готового ролика ПЕРЕД показом. Аналог verify() для каруселей.

    check_palette здесь неприменима по той же причине, что и в тёмном наборе:
    весь кадр — фотография, свои тона. Зато проверяемо то, что для Reels
    критично и чего глазом не увидишь наверняка:

    1. ТЕКСТ НА ЛИЦЕ. pick_zone обходит лица по построению, но он же и мог не
       найти чистого места (например, лицо занимает полкадра все 14 секунд) —
       тогда он положит текст в наименее плохое место, и это надо поймать.
       Вторая сеть, ровно как у обложек.
    2. ДЛИНА. Валерия задала 12-14 сек; длиннее — нарушение договорённости.
    3. ГЕОМЕТРИЯ И ЗВУК. 1080x1920 и наличие дорожки — то, что ломает загрузку
       молча.
    """
    import subprocess
    import imageio_ffmpeg

    problems, warnings = [], []
    out = meta.get("out")
    if not out or not os.path.exists(out):
        return ["ролик не собрался — файла %s нет. Сборка оборвалась раньше, "
                "чем дошла до записи: посмотрите выше по выводу первую красную "
                "строку, она и есть причина." % out]

    warnings += post_setup_warnings()      # BOX-73: завод донастроен не до конца

    if meta["dur"] > 14.05:
        problems.append("РОЛИК ДЛИННЕЕ ДОГОВОРЁННОСТИ: %.1f сек, а условлено "
                        "12-14 (решение Валерии). Лишнего %.1f сек — что "
                        "сделать: выберите кусок исходника покороче или уберите "
                        "один смысловой блок."
                        % (meta["dur"], meta["dur"] - 14.0))

    ff = imageio_ffmpeg.get_ffmpeg_exe()
    r = subprocess.run([ff, "-i", out, "-hide_banner"], capture_output=True,
                       text=True, encoding="utf-8", errors="replace")
    info = r.stderr or ""
    if "Audio:" not in info:
        problems.append("В РОЛИКЕ НЕТ ЗВУКА — Instagram примет такой ролик, но "
                        "зритель услышит тишину. Что сделать: проверьте, есть ли "
                        "звук в исходном клипе (откройте его плеером), либо "
                        "добавьте музыку при сборке (--music).")
    if "1080x1920" not in info:
        problems.append("КАДР НЕ 1080x1920%s — Reels ждёт вертикаль 9:16. Такое "
                        "бывает, когда ролик собрали не заводским путём: "
                        "повторите сборку с начала. Если повторится — это "
                        "поломка завода, а не вашего материала, напишите об этом."
                        % ("" if not _out_size(info)
                           else " (сейчас %s)" % _out_size(info)))
    # Флаг поворота на ВЫХОДЕ = ролик ляжет на бок у зрителя, хотя сам кадр верный:
    # ffmpeg применяет флаг источника при чтении и копирует его в результат, то есть
    # поворачивает дважды. Поймано на ролике №17; у роликов без флага не видно вовсе,
    # поэтому глазами это не проверяется — только так.
    if "displaymatrix" in info:
        problems.append("РОЛИК ЛЯЖЕТ НА БОК У ЗРИТЕЛЯ: на выходе остался флаг "
                        "поворота (displaymatrix) — у вас на компьютере кадр "
                        "выглядит правильно, а плеер соцсети повернёт его ещё "
                        "раз. Это поломка сборки, а не вашего материала: "
                        "пересоберите ролик; если повторится — в render() должен "
                        "стоять -metadata:s:v:0 rotate=0.")

    tx0, ty0, tx1, ty1 = meta["box"]
    hit = []
    for (fx0, fy0, fx1, fy1) in meta.get("faces", []):
        ox = max(0, min(tx1, fx1) - max(tx0, fx0))
        oy = max(0, min(ty1, fy1) - max(ty0, fy0))
        if ox > 0 and oy > 0:
            area = max(1, (fx1 - fx0) * (fy1 - fy0))
            hit.append(ox * oy / area * 100)
    if hit:
        problems.append("ТЕКСТ НА ЛИЦЕ: подпись закрывает до %.0f%% лица. "
                        "Свободного места в кадре нет ни на одной из %.1f сек — "
                        "поэтому подпись и легла на лицо. Что сделать: возьмите "
                        "другой клип (или другой кусок этого же), где человек "
                        "не занимает середину кадра, либо укоротите подпись — "
                        "короткий блок легче найдёт чистое место."
                        % (max(hit), meta["dur"]))
    if not meta.get("faces"):
        warnings.append("! лицо в ролике не распозналось — гляньте глазами, не "
                        "легла ли подпись на лицо: автоматика тут не помощник")

    for m in warnings:
        print("  ", m)
    if problems:
        msg = "\n".join("   - " + p for p in problems)
        if strict:
            raise CheckError("РОЛИК НЕ ПРОШЁЛ ПРОВЕРКИ ПЕРЕД ПОКАЗОМ — вот что "
                             "не так и что с этим сделать:\n" + msg)
        print("ЗАМЕЧАНИЯ ПРОВЕРОК (сборку не останавливаю):\n" + msg)
        return problems
    print("   проверки пройдены: %.1f сек, 1080x1920, звук на месте, "
          "текст лица не касается" % meta["dur"])
    return []


