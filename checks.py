def _grab_frame(out, t):
    """Один кадр ГОТОВОГО ролика в момент t → PIL.Image (или None, если ffmpeg
    не смог). Вынесено из _sample_output_faces (R21/R22): один и тот же кадр
    нужен и детектору лиц в окне реплики, и замеру контраста субтитра —
    тянуть его из файла дважды дорого."""
    import subprocess
    import tempfile
    import imageio_ffmpeg
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    with tempfile.TemporaryDirectory() as td:
        p = os.path.join(td, "f.png")
        r = subprocess.run([ff, "-y", "-ss", "%.2f" % t, "-i", out,
                            "-frames:v", "1", p], capture_output=True)
        if r.returncode != 0 or not os.path.exists(p):
            return None
        img = Image.open(p)
        img.load()            # файл сейчас удалится вместе с TemporaryDirectory
        return img


def _sample_output_faces(out, dur, times=None):
    """Лица на ГОТОВОМ ролике: сэмплим кадры САМОГО выхода и детектим mediapipe.

    Правило завода «смотри на результат, а не на лог»: координаты лиц берём из
    того, что реально увидит зритель (1080x1920), а не пересчитываем из исходника
    через геометрию композиции — так проверка не зависит от того, как компоновщик
    масштабировал спикера. Кадры тянем ffmpeg завода (cv2 не открывает h264-выход).

    times= — явные моменты сэмпла (R21: времена ВНУТРИ окна реплики); без них —
    прежняя сетка 10/30/50/70/90% длительности.
    """
    times = times or [round(max(0.1, dur * f), 2)
                      for f in (0.1, 0.3, 0.5, 0.7, 0.9)]
    faces = []
    for t in times:
        img = _grab_frame(out, t)
        if img is None:
            continue
        for box in face_boxes_img(img):
            faces.append((t, box))
    return faces


def _rel_luminance(a):
    """Относительная светимость WCAG для массива RGB 0..1 (линеаризация sRGB)."""
    c = np.where(a <= 0.03928, a / 12.92, ((a + 0.055) / 1.055) ** 2.4)
    return 0.2126 * c[..., 0] + 0.7152 * c[..., 1] + 0.0722 * c[..., 2]


def sub_contrast(img, box):
    """R22: контраст текст/фон в зоне субтитра кадра ГОТОВОГО ролика → ratio
    (как в WCAG: (L1+0.05)/(L2+0.05)) или None, если зона пуста/вырождена.

    E4-46: ЭТА ЖЕ формула живёт в движке (`engine_talk._sub_contrast_region`,
    он мерит её на каждом кадре реплики после вклейки спрайта). Две реализации
    обязаны давать одно число — иначе meta и гейт снова разъедутся по шкалам.

    Пиксели текста в зоне не размечены, поэтому оцениваем по светимости:
    «светлая сторона» = среднее верхнего дециля L (белый текст или светлая
    караоке-плашка), «тёмная сторона» = медиана нижней половины (фон под белым
    текстом или тёмный INK-текст на плашке). Караоке-плашка при этом НЕ
    штрафуется: светлая заливка на светлом фоне всё равно даёт пару
    «светлое↔тёмное» за счёт тёмного текста в ней — ловим ровно нечитаемость
    (в зоне нет светимостной пары), а не конкретный способ отрисовки.
    """
    a = np.asarray(img.convert("RGB"), dtype=np.float32) / 255.0
    ih, iw = a.shape[:2]
    x0, y0, x1, y1 = [int(v) for v in box]
    x0, y0 = max(0, x0), max(0, y0)
    x1, y1 = min(iw, x1), min(ih, y1)
    if x1 - x0 < 8 or y1 - y0 < 8:
        return None
    L = _rel_luminance(a[y0:y1, x0:x1]).ravel()
    if L.size < 64:
        return None
    hi_thr = np.percentile(L, 90)
    lo_half = L[L <= np.percentile(L, 50)]
    hi = float(L[L >= hi_thr].mean())
    lo = float(np.median(lo_half)) if lo_half.size else float(L.min())
    return (hi + 0.05) / (lo + 0.05)


# R25: СПЕЛЛ-СКРИНИНГ СУБТИТРОВ — эвристики БЕЗ словарей. hunspell-словари
# ru идут под GPL/LGPL/MPL в разных сборках — вендорить нельзя (правило
# лицензий MIT/BSD/Apache/OFL, словари включительно), поэтому ловим не
# «слово не в словаре», а ХАРАКТЕРНЫЕ артефакты распознавания речи. Только
# warning: у эвристик есть ложные срабатывания на именах/брендах — блокировать
# по ним рендер нельзя НИКОГДА (решение AUDIT R25).
_SPELL_VOWELS = set("аеёиоуыэюя")
_SPELL_OK_2CONS = {"ль", "нь", "св", "вс"}   # междометия/огрызки, законные в речи


def _spell_word_reason(w):
    """Причина подозрительности ОДНОГО слова или None. w — без пунктуации."""
    lw = w.lower()
    has_cyr = any("а" <= c <= "я" or c == "ё" for c in lw)
    has_lat = any("a" <= c <= "z" for c in lw)
    # 1. Смешение алфавитов в одном слове («приvет», «cтарт» с латинской c) —
    #    классика ASR/копипасты; целиком латинское слово (Instagram) законно.
    if has_cyr and has_lat:
        return "латиница внутри кириллицы"
    if not has_cyr:
        return None
    letters = [c for c in lw if "а" <= c <= "я" or c == "ё"]
    # 2. Обрывок: кириллическое слово из 2+ букв ВООБЩЕ без гласных («прв»,
    #    «тщкс») — так выглядят оборванные токены транскрипции. Исключения:
    #    аббревиатуры капсом (ВВП, СМС) и законные огрызки разговорной речи.
    if len(letters) >= 2 and not (_SPELL_VOWELS & set(letters)):
        if w.isupper() and len(letters) <= 5:
            return None
        if lw in _SPELL_OK_2CONS:
            return None
        return "нет гласных"
    # 3. Кластер согласных 5+ подряд («здрвствуйте») — в живых словах такие
    #    редки и почти все содержат -тств-/-льств-/-рств- (агентство,
    #    правительство, бодрствовать) — их пропускаем, чтобы не шуметь на
    #    законной лексике; у ASR-огрызка «здрвств» таких морфем нет.
    run = ""
    best = ""
    for c in letters:
        if c in _SPELL_VOWELS or c in "ъь":
            run = ""
        else:
            run += c
            if len(run) > len(best):
                best = run
    if (len(best) >= 5 and "тств" not in best and "льств" not in best
            and "рств" not in best):
        return "кластер согласных «%s»" % best
    return None


def spell_suspects(texts, user_words=None):
    """R25: подозрительные слова в текстах реплик → [(слово, причина)].

    texts — iterable строк (текст реплики); user_words — необязательный
    ПОЛЬЗОВАТЕЛЬСКИЙ словарь-белый список (имена, бренды, термины проекта),
    любые регистры. Слово, попавшее в белый список, не флагуется. Функция
    чистая и без внешних зависимостей — её же может звать talk_plan/оркестратор
    до рендера, не дожидаясь гейта.
    """
    allow = {str(u).lower() for u in (user_words or [])}
    seen, out = set(), []
    for text in texts or []:
        for tok in str(text).split():
            w = tok.strip(".,!?…—–-:;()[]«»\"'0123456789%+")
            if len(w) < 2 or w.lower() in allow or w.lower() in seen:
                continue
            reason = _spell_word_reason(w)
            if reason:
                seen.add(w.lower())
                out.append((w, reason))
    return out


def _cue_sample_times(t0, t1, dur, max_samples=3):
    """Моменты сэмпла ВНУТРИ окна реплики [t0, t1] (R21): короткая реплика —
    середина, длинная — до трёх точек (20/50/80%), всё в границах ролика."""
    t0, t1 = float(t0 or 0), float(t1 or 0)
    w = max(0.0, t1 - t0)
    fracs = ((0.5,) if (w <= 0.6 or max_samples <= 1)
             else (0.2, 0.5, 0.8)[:max_samples])
    times, seen = [], set()
    for f in fracs:
        t = round(min(max(0.05, t0 + w * f), max(0.05, dur - 0.05)), 2)
        if t not in seen:
            seen.add(t)
            times.append(t)
    return times


