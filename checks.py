def verify(out_dir, acc, cover_result, photo_slides=(), theme_slides=(), strict=True,
           slide_results=None):
    """
    out_dir      — папка со слайдами
    acc          — кортеж RGB акцента этой карусели
    cover_result — то, что вернул cover_*()
    photo_slides — номера слайдов на фото С ЧЕЛОВЕКОМ (их палитру не проверяем)
    theme_slides — номера ТЕМАТИЧЕСКИХ (непортретных) слайдов: b-roll/lifestyle-
                   кадры без человека. Их палитру тоже не проверяем.
    slide_results — необязательно: {номер_слайда: результат_функции_отрисовки}
                   для слайдов КРОМЕ обложки (обложка берётся из cover_result).
                   Когда передан, каждый слайд из него проходит check_face_safe
                   + check_text_bounds — жёсткий гейт «лицо не закрыто / текст
                   не вылезает за край» на ВСЕХ слайдах, а не только на входе.
                   Без него — прежнее поведение (проверяется только обложка на
                   лицо, границы не проверяются нигде): старые build_*.py,
                   которые не собирают возврат внутренних слайдов, не ломаются.

    ПРАВИЛО 2/3 (решение владельца, 01.08.2026): портретных слайдов (обложка +
    photo_slides − theme_slides) должно быть НЕ БОЛЕЕ 2/3 всех слайдов карусели.
    Оставшаяся треть+ — тематические кадры без человека (theme_slides) и/или
    текстовые слайды. Правило действует на ВСЕ карусели завода: скрипт-сборщик
    обязан объявить theme_slides, иначе полностью портретная карусель здесь
    падает и заставляет добавить непортретную треть.
    """
    import os
    problems, warnings = [], []
    warnings += post_setup_warnings()      # BOX-73: завод донастроен не до конца
    photo_like = set(photo_slides) | set(theme_slides)

    all_results = dict(slide_results or {})
    all_results[1] = cover_result
    for num, res in sorted(all_results.items()):
        label = "обложка" if num == 1 else "слайд %d" % num
        face_problems = check_cover_face(res) if num == 1 else check_face_safe(res, label=label)
        for p in face_problems:
            (warnings if p.startswith("!") else problems).append(p)
        problems += check_text_bounds(res, label=label)

    all_slides = []
    for f in sorted(os.listdir(out_dir)):
        if not f.endswith(".png"):
            continue
        n = int(os.path.splitext(f)[0])
        all_slides.append(n)
        if n == 1 or n in photo_like:
            continue
        problems += check_palette(os.path.join(out_dir, f), acc)

    # ПРАВИЛО 2/3: портрет = обложка ∪ photo_slides, минус объявленные тематические.
    total = len(all_slides)
    portrait = ({1} | set(photo_slides)) - set(theme_slides)
    portrait &= set(all_slides)
    if total and len(portrait) * 3 > total * 2:
        # Насколько превышено: d = 3p - 2n > 0. Заменить портрет на кадр без
        # человека — минус 3 к d (портрет ушёл, всего столько же); добавить
        # слайд без человека — минус 2 (всего стало больше). Отсюда два числа,
        # а не одно на глаз.
        p, n = len(portrait), total
        d = 3 * p - 2 * n
        swap = -(-d // 3)
        add = -(-d // 2)
        problems.append(
            "СЛИШКОМ МНОГО СЛАЙДОВ С ЧЕЛОВЕКОМ (правило 2/3): портретных %d из "
            "%d, а можно не больше %d. Что сделать — на выбор: (1) заменить %d "
            "%s с человеком на кадр без человека — и указать его номер в "
            "theme_slides; (2) добавить в карусель %d %s без человека "
            "(тематический кадр или текстовый слайд). Правило держит карусель "
            "про смысл, а не про фотосессию."
            % (p, n, (n * 2) // 3, swap,
               _plural(swap, "слайд", "слайда", "слайдов"), add,
               _plural(add, "слайд", "слайда", "слайдов")))

    for m in warnings:
        print("  ", m)
    if problems:
        msg = "\n".join("   - " + p for p in problems)
        if strict:
            raise CheckError("КАРУСЕЛЬ НЕ ПРОШЛА ПРОВЕРКИ ПЕРЕД ПОКАЗОМ — вот "
                             "что не так и что с этим сделать:\n" + msg)
        print("ЗАМЕЧАНИЯ ПРОВЕРОК (сборку не останавливаю):\n" + msg)
        return problems
    # ⚠️ БЕЗ СИМВОЛА «≤». Консоль Windows отдаёт cp1251, когда вывод
    # перехватывают (а оркестратор перехватывает всегда), и на этой строке
    # сборка падала UnicodeEncodeError — ПОСЛЕ того, как карусель собрана и
    # проверки прошли. Успех, отрапортованный кодом 1, — худший вид отказа.
    print("   проверки пройдены: цвет един, текст лица не касается%s, "
          "человек не более чем на 2/3 слайдов"
          % (" и не выходит за поле" if slide_results else " на обложке"))
    return []


