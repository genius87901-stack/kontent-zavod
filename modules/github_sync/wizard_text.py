# -*- coding: utf-8 -*-
"""Готовые тексты про резервную копию завода — для мастера установки.

Здесь ТОЛЬКО текст, никакой логики. Мастер установки (`skills/install/SKILL.md`)
может либо вставить его как есть, либо показать командой:

    python -m github_sync.wizard_text            # объяснение целиком
    python -m github_sync.wizard_text --short    # одна фраза-напоминалка
    python -m github_sync.wizard_text --phone    # что можно и чего нельзя с телефона

Текст держится здесь, чтобы правка формулировок не требовала трогать мастер.

⚠️ САМОЕ ВАЖНОЕ В ЭТИХ ТЕКСТАХ — раздел про телефон. Соблазн сказать «завод в
кармане» огромный, и он был бы враньём: собрать ролик в облаке нечем — там нет
ни сырья клиента, ни распознавания речи, ни ffmpeg, ни ключей. Человек, которому
пообещали телефон, попросит с него собрать рилс, получит отказ и решит, что
завод сломан. Формулировки ниже написаны так, чтобы граница была видна СРАЗУ.
"""
from __future__ import annotations

import sys

EXPLAINER = """\
Резервная копия завода — зачем она.

Сейчас ваш завод существует ровно в одном экземпляре: на этом компьютере.
Сломается диск, снесут папку, украдут ноутбук — вместе с ним пропадут и код,
и ваши смыслы, и контент-план. Восстанавливать будет неоткуда.

Копия на GitHub это чинит. GitHub — бесплатное хранилище для кода; репозиторий
будет ПРИВАТНЫМ, то есть видите его только вы.

Что в копии есть:
  • код завода и все настройки;
  • ваши смыслы (Content Bible), тексты, сценарии, контент-план;
  • пресеты оформления каруселей.

Чего в копии нет и не будет НИКОГДА:
  • ключей и паролей (файл .env не уезжает ни при каком раскладе);
  • ваших фото, видео и музыки — они и так лежат на Google Диске;
  • готовых роликов и каруселей.

Настройка одна: войти в свой GitHub. Я покажу ссылку и восьмизначный код —
откроете ссылку на телефоне или в браузере, войдёте, введёте код. Всё.
Аккаунта нет — заведёте бесплатно за минуту, там нужна только почта.

Дальше копия обновляется сама, каждый раз когда мы с вами начинаем работу.
"""

PHONE = """\
Что можно делать с телефона, а что нельзя.

Когда копия завода лежит на GitHub, вы можете открыть её в Claude Code с
телефона и работать. Но телефон НЕ становится заводом — и лучше знать это
сразу, чем упереться в отказ.

С ТЕЛЕФОНА РАБОТАЕТ:
  • смыслы — править Content Bible, дописывать распаковку;
  • тексты — посты, подписи, сценарии съёмки;
  • контент-план — смотреть, править, утверждать и снимать слоты;
  • разбор — читать отчёты и журналы, разбираться, что произошло;
  • сам код завода — если захотите что-то поменять.

С ТЕЛЕФОНА НЕ РАБОТАЕТ (и не заработает):
  • сборка каруселей и роликов;
  • нарезка эфиров и расшифровка речи;
  • публикация в соцсети.

Почему: чтобы собрать ролик, нужны ваши исходники, распознавание речи (около
2,7 ГБ), ffmpeg и ключи от соцсетей. Ничего этого в облаке нет — и ключи туда
специально не отправляются. Сборка и публикация остаются на компьютере.

Обычный порядок такой: с телефона придумали и написали → на компьютере завод
это собрал и опубликовал. Правку с телефона компьютер заберёт сам, а если
хотите сразу — скажите помощнику «забери правки с GitHub».
"""

SHORT = ("Копия завода на GitHub: код и смыслы продублированы, ключи и медиа "
         "не уезжают. С телефона — смыслы, тексты и план; сборка и публикация "
         "остаются на компьютере.")


def main() -> int:
    arg = sys.argv[1] if len(sys.argv) > 1 else ""
    if arg == "--short":
        print(SHORT)
    elif arg == "--phone":
        print(PHONE)
    else:
        print(EXPLAINER)
        print(PHONE)
    return 0


if __name__ == "__main__":
    sys.exit(main())
