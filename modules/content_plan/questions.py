def _resolve(value):
    """default может быть callable (читает конфиг) — вычисляем лениво."""
    return value() if callable(value) else value


def by_key(key: str):
    for q in QUESTIONS:
        if q["key"] == key:
            return q
    return None


def keys():
    return [q["key"] for q in QUESTIONS]


def defaults() -> dict:
    """Умолчания всех вопросов (конфиг + встроенные). Пустые (None) пропускаем —
    их не надо класть в бриф, иначе планировщик получит мусорный ключ."""
    out = {}
    for q in QUESTIONS:
        val = _resolve(q.get("default"))
        if val is None:
            continue
        out[q["key"]] = val
    return out


def validate_answer(key: str, value):
    """Проверка ответа против options. Возвращает (значение, предупреждение|None).

    Мягко: не из списка → берём как есть с предупреждением (клиент вправе
    назвать свою рубрику). Жёстко (strict=True, режим одобрения) → откатываемся
    на безопасный default, потому что незнакомый режим менять нельзя."""
    q = by_key(key)
    if q is None:
        return value, "неизвестный ключ %r — в бриф не попадёт" % key
    opts = _resolve(q.get("options")) or []
    if q.get("strict") and opts and value not in opts:
        return _resolve(q.get("default")), (
            "%s=%r не из списка (%s) — взят безопасный умолчательный %r"
            % (key, value, ", ".join(map(str, opts)), _resolve(q.get("default"))))
    return value, None


def merge_brief(answers: dict = None, base: dict = None):
    """Собирает бриф: умолчания ← прошлый бриф (base) ← новые ответы.

    Так интервью переиспользуется: сохранённый brief.json подкладывается как
    base, и клиенту достаточно назвать только то, что он меняет.
    Возвращает (brief, список предупреждений)."""
    warns = []
    brief = defaults()
    for src in (base or {}, answers or {}):
        for key, value in src.items():
            if key == "period":          # период не вопрос — считается из горизонта
                brief["period"] = value
                continue
            if by_key(key) is None:
                warns.append("ключ %r не из списка вопросов — пропущен" % key)
                continue
            value, warn = validate_answer(key, value)
            if warn:
                warns.append(warn)
            if value is None:
                brief.pop(key, None)
            else:
                brief[key] = value
    return brief, warns


def render(prefix: str = "") -> str:
    """Человекочитаемая распечатка интервью — для показа клиенту в диалоге."""
    lines = []
    for i, q in enumerate(QUESTIONS, 1):
        lines.append("%s%d. %s" % (prefix, i, q["ask"]))
        opts = _resolve(q.get("options")) or []
        if opts:
            lines.append("%s   варианты: %s%s"
                         % (prefix, " | ".join(str(o) for o in opts),
                            "  (только из списка)" if q.get("strict") else ""))
        dflt = _resolve(q.get("default"))
        if dflt is None or dflt == [] or dflt == {}:
            lines.append("%s   по умолчанию: пропустить" % prefix)
        elif isinstance(dflt, (list, tuple)):
            lines.append("%s   по умолчанию: %s"
                         % (prefix, ", ".join(str(x) for x in dflt)))
        else:
            lines.append("%s   по умолчанию: %s" % (prefix, dflt))
        if q.get("help"):
            lines.append("%s   зачем: %s" % (prefix, q["help"]))
        lines.append("")
    return "\n".join(lines).rstrip()


