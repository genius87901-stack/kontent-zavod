"""Модуль analytics — аналитика УЖЕ опубликованного контента + рекомендации.

Что делает:
  * собирает метрики вышедших постов (охваты, показы, досмотр/удержание, реакции,
    сохранения, репосты, переходы по ссылке) через абстракцию источника
    (providers.fetch_metrics) — по одному провайдеру на площадку (IG / TG / VK).
    Живой сбор идёт через Upload-Post — тот же сервис, что публикует контент
    (live.py + upload_post.py): пост находится по сохранённому при публикации
    request_id, метрики берутся из пачки снимков, которая не дёргает площадки.
    Живой путь стоит ЗА ФЛАГОМ analytics_metrics_source и требует ключ;
  * НЕ ЛОМАЕТСЯ без сети и без ключа — а это офлайн-установка клиента. Лестница
    деградации: живой ответ → последний успешный ответ из кэша (cache.py) →
    образец из карточки → честное «данных нет» с причиной по-русски. Ретраи с
    бэкоффом только на поправимое (сеть/429/5xx), таймауты, никаких повторов на
    401/404. Нет ключа — в сеть не идём вообще, чужой платный аккаунт не жжём;
  * хранит нормализованные метрики в своей папке (json-хранилище analytics/) и
    дописывает КАЖДЫЙ замер в историю (history.py), чтобы была видна динамика
    поста, а не только срез «сейчас»;
  * прогоняет ДЕТЕРМИНИРОВАННЫЙ движок рекомендаций «метрика → совет»
    (recommender.py): низкий досмотр → усилить хук/сократить, мало переходов →
    явный CTA/кодовое слово, охват ниже среднего → время выхода/обложка и т.д.
    «Умный» шаг вынесен в явный хук `recommender.llm_advice` (по образцу
    `planner.llm_ideas` / `writer.llm_script`): по умолчанию отдаёт
    детерминированную базу и платный API НЕ зовёт.

ЗАМЕР, НЕ ВЫВОД: модуль ничего не публикует и не меняет. Он лишь читает метрики и
советует эксперту, что поменять в следующих постах. Петля обратной связи с
планировщиком (`content_plan.planner`) описана в DESIGN.md — сам planner модуль
НЕ трогает, только предлагает подсказки в свой файл.

ГРАНИЦЫ (CONTRACT.md §3): input() нет, секретов нет, абсолютных путей нет — всё от
корня установки через pathlib (Windows в том числе), pip: [] (только stdlib).
Ключ Upload-Post читается как в publishing (окружение → .env корня установки), в
код и лог не попадает. Подробности — в DESIGN.md §7 рядом; офлайн-тесты живого
сбора на записанных ответах API — python -m analytics.test_live.
"""
