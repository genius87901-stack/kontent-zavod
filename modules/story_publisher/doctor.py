def _ffmpeg_ok():
    """Есть ли ffmpeg ТАМ, ГДЕ ЕГО БЕРЁТ ЗАВОД (BOX-51).

    Порядок ровно как в build_slideshow.py и modules/publishing/doctor.py::
    _ffmpeg_ok: сначала бинарь из пакета imageio-ffmpeg (он едет в комплекте и
    является штатным путём завода), и только потом системный — необязательный
    запасной вариант.

    ЧТО БЫЛО НЕ ТАК. Проверка была `shutil.which("ffmpeg")`, то есть искала
    ffmpeg в PATH. В коробке его там нет НИКОГДА (ставится пакетом, не в PATH),
    поэтому на полностью рабочей машине доктор заявлял «часть возможностей
    недоступна» и уходил с кодом 2 — владельцу это приезжало строкой про
    деградацию, которой не было. Тот же случай уже чинили в publishing.
    """
    try:
        import imageio_ffmpeg
        if Path(imageio_ffmpeg.get_ffmpeg_exe()).exists():
            return True
    except Exception:          # пакета нет или бинарь не распаковался
        pass
    return shutil.which("ffmpeg") is not None


# ── «чем доставить» под ТЕКУЩУЮ ОС (BOX-18) ──────────────────────────────────
# На маке команды winget не существует, и клиент упирался в тупиковую подсказку.
# ОС определяем ЕДИНЫМ принятым в проекте способом — install/check_env.py
# (detect_os + manifest_hint + ключи <os>_install из module.manifest.json).
# Своего определения ОС не заводим.
# Windows-путь не меняется: там возвращается windows_install из манифеста, а он
# совпадает с текстом, что был зашит здесь раньше; при любой неудаче — прежний текст.
_CHECK_ENV_CACHE = []      # [] — ещё не грузили; [mod|None] — загружено


def _check_env_module():
    """install/check_env.py как модуль (он не пакет и не лежит на PYTHONPATH)."""
    if _CHECK_ENV_CACHE:
        return _CHECK_ENV_CACHE[0]
    mod = None
    try:
        import importlib.util
        for parent in Path(__file__).resolve().parents:
            cand = parent / "install" / "check_env.py"
            if cand.is_file():
                spec = importlib.util.spec_from_file_location("factory_check_env", cand)
                if spec is not None and spec.loader is not None:
                    mod = importlib.util.module_from_spec(spec)
                    spec.loader.exec_module(mod)
                break
    except Exception:
        mod = None
    _CHECK_ENV_CACHE.append(mod)
    return mod


def _manifest_binary(name):
    """Запись system_binaries своего модуля по имени бинарника (или None)."""
    try:
        man = Path(__file__).resolve().parent / "module.manifest.json"
        data = json.loads(man.read_text(encoding="utf-8-sig"))
        for b in data.get("system_binaries", []) or []:
            if (b.get("name") or "").strip().lower() == name:
                return dict(b)
    except Exception:
        pass
    return None


def _install_hint(name, windows_hint):
    """Команда установки `name` для текущей ОС: winget / brew / apt."""
    ce = _check_env_module()
    if ce is None:
        return windows_hint
    try:
        os_key = ce.detect_os()
        entry = _manifest_binary(name) or {"name": name}
        if os_key == "windows":
            return (entry.get("windows_install") or "").strip() or windows_hint
        return ce.manifest_hint(entry, os_key)
    except Exception:
        return windows_hint


def run():
    print("Проверка модуля сторис (story-publisher)")
    print("-" * 48)

    # 1) Структурная целостность. Единственный случай кода 1: сама проверка не
    #    может отработать — модуль не импортируется или не виден корень установки.
    try:
        from .config import config_for, install_root
        from .drivers import known_platforms  # noqa: F401
    except Exception:  # pragma: no cover - структурная поломка
        print("СБОЙ: модуль повреждён и не запускается — сторис не будут "
              "собираться и публиковаться вообще. Переустановите систему "
              "из свежего архива.")
        return 1

    try:
        root = install_root()
        cfg = config_for(None)  # клиент по умолчанию
    except Exception:  # pragma: no cover
        print("СБОЙ: не удалось определить корень установки — проверка не может "
              "отработать. Переустановите систему из свежего архива.")
        return 1

    print("Корень установки: %s" % root)

    # Чего не хватает для боевой публикации. Непустой список = урезанный режим
    # (код 2): главный путь — сборка сторис — работает всегда.
    limits = []

    config_file = root / "config" / "factory.config.json"
    if not config_file.exists():
        # Само по себе отсутствие файла настроек ещё ни о чём не говорит:
        # секреты площадок живут в окружении (.env), а не в этом файле. Реальную
        # деградацию ловят проверки площадок ниже — иначе доктор соврал бы
        # «сторис никуда не уйдут» на настроенном через окружение заводе.
        print("• Настройки ещё не заданы (config/factory.config.json нет). "
              "Несекретные ответы установки берутся оттуда; ключи площадок "
              "читаются из окружения и проверяются ниже отдельно.")

    # 2) ffmpeg (готовит/проверяет медиа). Не критично для публикации готового
    #    файла, но лучше иметь. В манифесте это system_binaries без required —
    #    трактуем как необязательный: по CONTRACT §2 это код 2, а не 1.
    if not _ffmpeg_ok():
        print("• FFmpeg не найден ни пакетом, ни в системе. Почините: "
              "pip install imageio-ffmpeg==0.6.0 (либо системный: %s). "
              "Без него часть проверок медиа недоступна: система не сможет "
              "убедиться, что видео подходит под сторис (9:16, длительность) — "
              "публикация пойдёт, но кривой ролик отсечётся уже площадкой."
              % _install_hint("ffmpeg", "winget install Gyan.FFmpeg"))
        limits.append("нет FFmpeg — проверка видео перед отправкой недоступна")

    # 2a) Движок сборки сторис. Основной путь — вызов engine_photo проекта;
    #     если его нет, работает автономный запасной рендер (сборка не падает).
    try:
        from .story_builder import load_engine
        if load_engine() is not None:
            print("✓ Движок сборки сторис: engine_photo подключён (кадры 1080×1920).")
        else:
            print("• Движок сборки сторис: engine_photo недоступен — сборка "
                  "пойдёт автономным запасным рендером (тоже 1080×1920).")
    except Exception:  # pragma: no cover - сборка не критична для доктора
        print("• Движок сборки сторис: недоступен, будет запасной рендер.")

    # 3) Готовность по площадкам (секреты — только факт наличия).
    #
    # ⚠️ КЛЮЧИ ЗДЕСЬ ОБЯЗАНЫ СОВПАДАТЬ С ТЕМИ, ЧТО ЧИТАЮТ ДРАЙВЕРЫ, и лежать в
    # тех же местах. Раньше доктор спрашивал только окружение и только точное имя
    # `tg_story_chat_id`/`tg_chat_id`: клиент отвечал мастеру на вопрос про канал
    # (publishing, ключ `TG_CHAT_ID`, несекретный → уезжает в
    # config/factory.config.json), а доктор всё равно писал «не задан канал» и
    # уводил модуль в урезанный режим. Теперь и доктор, и драйвер спрашивают
    # any_value(): оба имени, оба источника, без учёта регистра.
    up_key = cfg.has_secret("upload_post_api_key")
    up_user = cfg.has_any("upload_post_user")
    # ОДИН КЛЮЧ ВК НА ВЕСЬ ЗАВОД. Канон — vk_user_token_kate (его читают
    # vkcarousel.py и vkpost.py, на нём прошли живые публикации); vk_stories_token
    # — прежнее имя того же ключа, оставлено алиасом ради уже установленных копий.
    # Порядок именно такой: сначала канон. Оба имени проверяем ровно потому, что
    # оба читает drivers/vk.py — разойтись доктору и драйверу нельзя.
    vk_token = cfg.has_any("vk_user_token_kate", "vk_stories_token")
    tg_token = cfg.has_secret("tg_bot_token")
    tg_chat = cfg.has_any("tg_story_chat_id", "tg_chat_id")

    # Instagram
    if up_key and up_user:
        print("✓ Instagram: готов к публикации сторис.")
    else:
        miss = []
        if not up_key:
            miss.append("ключ Upload-Post")
        if not up_user:
            miss.append("профиль Upload-Post")
        print("• Instagram: не заполнено — %s. Сторис в Instagram публиковаться "
              "не будут: готовый кадр придётся выкладывать вручную с телефона. "
              "Остальное работает." % ", ".join(miss))
        limits.append("Instagram (не заполнено: %s)" % ", ".join(miss))

    # Telegram
    #
    # ПОРЯДОК ВЕТОК ПОВТОРЯЕТ ПОРЯДОК В ДРАЙВЕРЕ. drivers/telegram.py сначала
    # смотрит business connection и, если он есть, публикует НАСТОЯЩУЮ Story
    # через postStory — и только без него падает на пост в канал. Доктор эту
    # ветку не знал и рапортовал «пост в канал» тогда, когда завод на самом
    # деле выкладывал историю (замечено 01.09.2026 сверкой пробного прогона с
    # ответом доктора). Расхождение доктора с драйвером — худший вид ошибки в
    # этом модуле: клиент верит доктору, а происходит другое.
    tg_business = cfg.has_secret("tg_business_connection_id")
    if tg_token and tg_business:
        print("✓ Telegram: готов к НАСТОЯЩЕЙ истории в бизнес-аккаунт "
              "(postStory) — не пост в канал, а полноценная Story на 24 часа.")
    elif tg_token and tg_chat:
        print("✓ Telegram: готов через собственного бота (Bot API завода) — "
              "пост творческого в канал. Это не нативная Story.")
        print("  Хотите настоящую историю вместо поста: нужен Telegram Premium "
              "с бизнес-аккаунтом, бот в бизнес-режиме у @BotFather и разрешение "
              "на истории в «Telegram для бизнеса → Чат-боты». После этого "
              "появится tg_business_connection_id, и завод переключится сам.")
    elif tg_token and not tg_chat:
        print("• Telegram: токен бота есть, но не задан канал. Укажите @-адрес "
              "канала — и публикация пойдёт (вопрос установки «Канал Telegram "
              "для сторис», либо общий «Адрес канала Telegram-архива»). Пока "
              "канала нет, творческое в Telegram не уходит.")
        limits.append("Telegram (не указан канал)")
    elif up_key and up_user:
        print("✓ Telegram: пойдёт через Upload-Post (пост в канал, не Story).")
    else:
        print("• Telegram: нет ни своего бота, ни ключа Upload-Post — "
              "публикация в Telegram недоступна, выкладывать придётся вручную.")
        limits.append("Telegram (нет ни бота, ни ключа Upload-Post)")

    # VK
    #
    # ⚠️ ЧЕСТНОСТЬ ПРО «ГОТОВ». Ключ на месте — это не то же самое, что «сторис
    # выйдет». Путь stories.* (getUploadServer → загрузка файла → stories.save)
    # написан по документации и НИ РАЗУ не проходил живьём: неизвестно, даёт ли
    # аккаунт клиента право на публикацию историй через API и то ли имя у поля
    # загрузки. Молчать об этом нельзя — клиент решит, что сторис выходят сами,
    # и узнает обратное, только не обнаружив их у себя в профиле.
    # 🔴 ЛИЧНАЯ СТРАНИЦА ВК ЗАКРЫТА ЗАПРЕТОМ ОТ 08.09.2026. Путь stories.* жил
    # на ключе, который добывался прямым входом через чужое мобильное
    # приложение, а этот вход запрещён: после него ВКонтакте блокирует аккаунт
    # клиента целиком. Доктор БОЛЬШЕ НЕ ТРЕБУЕТ этот ключ и не зовёт его
