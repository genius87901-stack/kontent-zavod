# -*- coding: utf-8 -*-
"""Готовые тексты про диск клиента — для мастера установки.

Здесь ТОЛЬКО текст, никакой логики. Мастер установки (`skills/install/SKILL.md`,
владелец — ветка C2) может:
    * либо вставить текст к себе как есть (скопировать из этого файла),
    * либо показать его командой, ничего не копируя:

        python -m intake.wizard_text            # объяснение + дерево папок
        python -m intake.wizard_text --short    # одна фраза-напоминалка
        python -m intake.wizard_text --tree     # только дерево

Текст держится здесь, чтобы при изменении структуры диска мастер править
не пришлось — он читает актуальную версию.
"""
from __future__ import annotations

import sys

# Основной экран: показывается один раз, на этапе 1, сразу после того как
# структура на диске создана. Влезает в экран, без простыни.
DRIVE_EXPLAINER = """\
Готово — на вашем Google Диске появилась папка «КонтентЗавод».
Это единственное место, где мы с вами встречаемся: вы кладёте съёмку, я забираю
её оттуда и туда же возвращаю готовое. Ничего устанавливать на телефон не нужно.

Как это работает, если совсем коротко:

  1 Сырьё            — сюда вы кидаете съёмку с телефона.
                       Внутри подпапки: «Говорящие видео» (где вы говорите в камеру),
                       «Фото», «Видео для вставок», «Музыка», «Тексты и заметки».
                       Не уверены, куда — киньте в «1 Сырьё», я разберу.

  2 На утверждение   — сюда я кладу готовые черновики. Это ваша папка «посмотреть».
                       Понравилось — перетащите в «Одобрено».
                       Нет — в «Вернуть на правки» и рядом текстовый файл, что не так.

  3 Готово к публикации — то, что вы одобрили и что готово выходить.
  4 Опубликовано     — архив по месяцам: что и когда вышло.
  5 Смыслы и настройки — ваша книга смыслов и темы. Читать можно, править — по инструкции.
  НЕ_ТРОГАТЬ         — мои рабочие файлы. Туда заходить не нужно.

Три правила, и всё:
  • Кидаете только в «1 Сырьё». Забираете только из «2 На утверждение».
  • Файлы не переименовывайте — я узнаю их сам.
  • Ничего не публикуется, пока вы не скажете. Одобрение — это ваше слово.

В каждой папке лежит файл «ЧТО СЮДА КЛАСТЬ.txt» — если забудете, откройте его.\
"""

# Короткая напоминалка: для итогов этапа, писем, повторных запусков.
DRIVE_EXPLAINER_SHORT = (
    "Съёмку с телефона кидайте в «КонтентЗавод / 1 Сырьё», "
    "готовое забирайте из «2 На утверждение»: понравилось — в «Одобрено», "
    "нет — в «Вернуть на правки». Без вашего одобрения ничего не публикуется."
)

# Что сказать, если клиент спросит «а можно я переложу файлы?»
DRIVE_RULES_DONT = (
    "Чего делать не надо: переименовывать файлы, переставлять папки местами, "
    "заходить в «НЕ_ТРОГАТЬ» и удалять оттуда что-либо. Если удалить служебное — "
    "завод переделает уже сделанную работу заново."
)


def _tree() -> str:
    try:  # штатный путь: python -m intake.wizard_text
        from intake.drive_layout import render_tree
    except ImportError:  # запуск файлом напрямую
        from pathlib import Path
        sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
        from intake.drive_layout import render_tree
    return render_tree()


def full_text(with_tree: bool = False) -> str:
    """Полный экран объяснения; при with_tree — плюс дерево папок как есть."""
    if not with_tree:
        return DRIVE_EXPLAINER
    return DRIVE_EXPLAINER + "\n\nДерево папок целиком:\n\n" + _tree()


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if "--short" in argv:
        print(DRIVE_EXPLAINER_SHORT)
    elif "--tree" in argv:
        print(_tree())
    elif "--dont" in argv:
        print(DRIVE_RULES_DONT)
    else:
        print(full_text(with_tree="--with-tree" in argv))
    return 0


if __name__ == "__main__":
    sys.exit(main())
