def render(prefix: str = "") -> str:
    lines = []
    for i, q in enumerate(QUESTIONS, 1):
        lines.append("%s%d. %s" % (prefix, i, q["ask"]))
        if q.get("example"):
            lines.append("%s   пример: %s" % (prefix, q["example"]))
        if q.get("help"):
            lines.append("%s   зачем: %s" % (prefix, q["help"]))
    return "\n".join(lines)


