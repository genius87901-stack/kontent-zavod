# -*- coding: utf-8 -*-
"""Чтение КНИГИ СМЫСЛОВ проекта (Content Bible) для сценариста.

Self-contained (не тянет чужие модули): читает тот же источник, что и
content_plan (CONTENT_BIBLE_*.md), но своим кодом — граница владения по файлам
(CONTRACT.md §5) остаётся чистой. Достаём из книги:
  * кодовое слово CTA («Напишите слово РОСТ» → РОСТ);
  * банк хуков (секция про хуки для Reels) — конкретные первые фразы;
  * РЕАЛЬНЫЕ ФРАЗЫ ПО РУБРИКАМ (секция про темы для постов) — темы «его голосом»
    и на его фактах, разложенные по рубрикам сценариста. Это главный рычаг
    качества: сценарий строится из формулировок клиента, а не только из общих
    заготовок модуля;
  * якорный факт-актив (реальный кейс из книги, не выдумка).

ВАЖНО (BUG-2026-08-08, баг-репорт клиента Елены Сокольской): книга смыслов
каждого клиента — СВОЙ документ, своя ниша, свой рубрикатор, своя манера
формулировать CTA. Заголовки секций здесь ищутся ГИБКО (по ключевым словам, а
не по точной фразе одного примера-донора), а названия рубрик берутся ИЗ ФАЙЛА
КЛИЕНТА ДОСЛОВНО — без сверки со списком из семи рубрик Валерии. Если что-то
не нашлось — поле остаётся честно пустым/дефолтным, а не подменяется чужими
данными молча: смотри ключ "warnings" в результате load_bible().

Нет файла / битый файл → урезанный режим (дефолтное кодовое слово, пустой банк
хуков и тем), а НЕ падение — как и весь модуль. Пути — от корня установки, без
абсолютных путей и без сети.
"""
from __future__ import annotations

import re
from pathlib import Path

# ⚠️ Дефолтов-подстановок здесь БОЛЬШЕ НЕТ, и добавлять их сюда нельзя.
# До 08.08.2026 тут лежали кодовое слово Валерии («РОСТ») и её кейс («136 точек
# роста»). Первую версию починки они пережили: подстановка осталась в ветке
# «файла книги смыслов нет вовсе» — а это ровно то состояние, в котором коробка
# приезжает КАЖДОМУ клиенту до первого запуска bible_setup.py. То есть чужие
# данные получали все шесть клиенток по умолчанию.
# Правило: не знаем — отдаём пустое и говорим об этом. Пустое поле сценарист
# превращает в явную пометку-задание, чужое — в реплику, которую эксперт
# произнесёт в камеру и не заметит.
DEFAULT_CODE_WORD = ""
DEFAULT_ANCHOR = ""

# ── ЧТО СЧИТАЕМ ЗАГОЛОВКОМ СЕКЦИИ ───────────────────────────────────────────
# BUG-2026-08-10. До этой даты заголовок опознавался ТОЛЬКО как «# » или «## ».
# Живые книги клиентов оформлены иначе: «### 50 ХУКОВ», «**50 ХУКОВ**», строка
# «50 ХУКОВ ДЛЯ REELS» заглавными вовсе без разметки, с эмодзи или номером
# впереди. Для парсера таких секций не существовало вообще — клиентка видела
# «хуков в банке: 0, тем по рубрикам: 0» и не понимала, что не так с её файлом.
#
# Оформление теперь не важно, СМЫСЛОВЫЕ условия — прежние и НЕ ослаблены:
# хуки — корень «хук»; темы — «тем…» вместе с «пост…» или «рубрик…».
#
# Главный риск обратной стороны — ложное срабатывание: строка «Хук должен
# цеплять за 2 секунды» посреди абзаца НЕ должна становиться заголовком.
# Поэтому кандидат в заголовки обязан быть КОРОТКОЙ ОТДЕЛЬНОЙ строкой, а без
# разметки (# или **) — ещё и набранной ЗАГЛАВНЫМИ (либо «Раздел N …»).

#: длиннее — это уже фраза из текста, а не заголовок раздела.
_MAX_HEADER_CHARS = 80

#: «#…###### Заголовок» (любой уровень, с необязательными решётками в конце)
_MD_HEADER_RE = re.compile(r"^[ \t]{0,3}(#{1,6})[ \t]*(.*?)[ \t]*#*[ \t]*$")
#: строка целиком в **жирном** или __подчёркивании__ (часть строки — не заголовок)
_BOLD_ONLY_RE = re.compile(r"^(?:\*\*(?P<a>[^*]+?)\*\*|__(?P<b>[^_]+?)__)"
                           r"[ \t]*[:：]?$")
#: горизонтальная линейка — не заголовок, но «пустая строка» для соседей снизу
_RULE_RE = re.compile(r"^[-=*_]{3,}$")
#: «Раздел 2 — Хуки», «Часть 3. Темы для постов» — заголовок без разметки,
#: опознаваемый по служебному слову с номером, а не по регистру.
_SECTION_WORD_RE = re.compile(r"^(?:раздел|часть|блок|секция)\b[ \t]*[№#]?[ \t]*\d",
                              re.IGNORECASE)

# Смысловые условия (по тексту заголовка, без оформления). Не ослаблять:
# именно они держат оборону от ложных секций.
_HOOKS_TITLE_RE = re.compile(r"хук\w*", re.IGNORECASE)
#: Темы. Две формы, обе с защитой от ложных секций (BOX-52):
#:   1) «100 тем для постов», «темы по рубрикам» — слово «тем…» ВМЕСТЕ с
#:      «пост…»/«рубрик…»;
#:   2) «100 ТЕМ» — число + слово «тем» ЦЕЛИКОМ. Заголовок ровно такой формы
#:      прислала клиентка 11.08.2026: патч 1.3.5 научился видеть её «### 50
#:      ХУКОВ», а «### 100 ТЕМ» по-прежнему не считал секцией, и темы у неё
#:      оставались нулём. Граница `\b` держит оборону: «5 ТЕМНЫХ ПАТТЕРНОВ»
#:      секцией тем НЕ становится.
_THEMES_TITLE_RE = re.compile(
    r"(?:(?=.*\bтем\w*)(?=.*(?:пост\w*|рубрик\w*))"
    r"|^\W*\d{1,4}[ \t]+тем(?:а|ы|у|е)?\b)",
    re.IGNORECASE)

#: Строка-пункт списка внутри секции: «1. …», «1) …», «- …», «• …», «* …».
#: До BOX-52 брались ТОЛЬКО «1. …»: книга, набранная дефисами, читалась как
#: пустая при полностью распознанных заголовках. `**Жирный**` под это не
#: подходит (после звёздочки нужен пробел), линейка `---` — тоже.
_ITEM_RE = re.compile(r"^[ \t]*(?:\d{1,3}[.)]|[-–—•*])[ \t]+(.+?)[ \t]*$")


def _looks_all_caps(s: str) -> bool:
    """Строка набрана ЗАГЛАВНЫМИ (буквы есть, строчных нет)."""
    letters = [c for c in s if c.isalpha()]
    return len(letters) >= 3 and all(c.isupper() for c in letters)


def _strip_decor(title: str) -> str:
    """Снять обёртку **…**/__…__ с текста заголовка: на смысл она не влияет."""
    t = title.strip()
    m = _BOLD_ONLY_RE.match(t)
    if m:
        t = (m.group("a") or m.group("b")).strip()
    return t


def _scan_headers(lines: list) -> list:
    """Все строки-заголовки книги: [(номер строки, ранг, текст заголовка)].

    РАНГ — глубина вложенности, по нему секция понимает, где она кончается и
    что внутри неё подрубрика. У markdown-заголовка ранг = число решёток.
    Заголовки БЕЗ решёток ранжируются ЗАВЕДОМО ГЛУБЖЕ самой глубокой решётки в
    этом же документе: иначе «**Здоровье**» внутри «### 100 ТЕМ» оборвал бы
    секцию вместо того, чтобы стать её рубрикой. В документе вовсе без решёток
    заглавные идут за верхний уровень (1), жирные не-заглавные — за второй (2):
    так книга, целиком набранная жирным, разбирается на секции и рубрики.
    """
    md, plain = [], []
    prev_blank = True                     # начало файла = «сверху пусто»
    for i, raw in enumerate(lines):
        s = raw.strip()
        if not s:
            prev_blank = True
            continue
        standalone, prev_blank = prev_blank, bool(_RULE_RE.match(s))
        m = _MD_HEADER_RE.match(s)
        if m and m.group(2).strip():
            # Решётка — однозначная разметка заголовка, длину тут не меряем:
            # ограничение длины сузило бы поиск против того, как было до правки.
            title = _strip_decor(m.group(2))
            if title:
                md.append((i, len(m.group(1)), title))
            continue
        if len(s) > _MAX_HEADER_CHARS:    # длинная строка — это абзац
            continue
        bm = _BOLD_ONLY_RE.match(s)
        if bm:
            title = (bm.group("a") or bm.group("b")).strip()
            if title:
                plain.append((i, _looks_all_caps(title), title))
            continue
        if not standalone:                # строка внутри абзаца/списка — не заголовок
            continue
        if _looks_all_caps(s) or _SECTION_WORD_RE.match(s):
            plain.append((i, True, s))

    max_md = max((lvl for _i, lvl, _t in md), default=0)
    rank_caps = max_md + 1 if max_md else 1
    rank_soft = max_md + 2 if max_md else 2
    out = [(i, lvl, t) for i, lvl, t in md]
    out += [(i, rank_caps if caps else rank_soft, t) for i, caps, t in plain]
    out.sort(key=lambda it: it[0])
    return out


def _find_section(headers: list, title_re) -> tuple:
    """Первый заголовок, подходящий по СМЫСЛУ. (номер строки, ранг) или (None, None)."""
    for idx, rank, title in headers:
        if title_re.search(title):
            return idx, rank
    return None, None


def _section_end(headers: list, idx: int, stop_rank: int, total: int) -> int:
    """Где кончается секция: следующий заголовок ранга не глубже stop_rank."""
    for j, rank, _t in headers:
        if j > idx and rank <= stop_rank:
            return j
    return total


def _bible_default_path() -> Path:
    """Путь к книге смыслов по умолчанию — от корня установки (config.bible_file)."""
    try:
        from . import config
        return config.install_root() / config.bible_file()
    except Exception:
        # Аварийный путь, когда конфиг вообще недоступен. Имя нейтральное —
        # просить клиента положить в корень файл с именем другого человека нельзя.
        return Path(__file__).resolve().parents[2] / "КНИГА_СМЫСЛОВ.md"


def load_bible(bible_path=None, text=None) -> dict:
    """Читает книгу смыслов. Возвращает dict:
        {"code_word": str, "hooks": [str, ...],
         "themes": {rubric: [phrase, ...]}, "anchor": str, "ok": bool,
         "warnings": [str, ...]}
    Урезанный режим при отсутствии/битом файле (ok=False).

    `text` — прямая инъекция содержимого (для тестов); в бою не передаётся,
    читается файл по `bible_path`/дефолтному пути."""
    if text is None:
        path = Path(bible_path) if bible_path else _bible_default_path()
        try:
            text = path.read_text(encoding="utf-8-sig")
        except (OSError, ValueError):
            return {"code_word": DEFAULT_CODE_WORD, "hooks": [], "themes": {},
                    "anchor": DEFAULT_ANCHOR, "ok": False,
                    "warnings": ["Книга смыслов не подключена — сценарист соберёт "
                                 "только каркас: кодовое слово и кейс останутся "
                                 "пометками-заданиями, а не чужими данными. "
                                 "Подключить: python bible_setup.py --install"]}
    warnings = []
    code_word = _parse_code_word(text, warnings)
    hooks = _parse_hooks(text, warnings)
    themes = _parse_themes_by_rubric(text, warnings)
    anchor = _parse_anchor(text, warnings)
    return {
        "code_word": code_word,
        "hooks": hooks,
        "themes": themes,
        "anchor": anchor,
        "ok": True,
        "warnings": warnings,
    }


def section_headers(bible_path=None, text=None) -> list:
    """Заголовки, которые парсер РЕАЛЬНО видит в книге, в порядке файла.

    Нужна для самодиагностики (`bible_setup.py --status`): когда хуков и тем
    ноль, человек должен увидеть на экране, что именно принято за заголовки, —
    и сам понять, почему его раздел не опознан. Отдаём ТОЛЬКО строки-заголовки:
    содержимое книги клиента наружу не показываем.
    """
    if text is None:
        if not bible_path:
            return []
        try:
            text = Path(bible_path).read_text(encoding="utf-8-sig")
        except (OSError, ValueError):
            return []
    return [title for _i, _rank, title in _scan_headers(text.splitlines())]


def _parse_code_word(text: str, warnings: list) -> str:
    """Кодовое слово CTA из книги смыслов. Не нашли — ПУСТО + предупреждение.

    Явная пометка «Кодовое слово: X» — ПЕРВЫЙ и самый надёжный путь (симметрично
    «Якорный кейс: …», см. _parse_anchor): это то, что просим написать клиента
    в 02_РАСПАКОВКА_ВОПРОСЫ.md, работает в любой нише, результат предсказуем,
    не зависит от того, как человек оформил призыв в остальном тексте книги.
    Остальные паттерны — запасной путь для книг, написанных до этой пометки
    (донор Валерии оформлен оборотом «Напишите слово «X»», не меткой)."""
    patterns = [
        r"^[ \t]*кодов\w*\s+слов[оа][ \t]*[:：—–-][ \t]*«?([А-ЯЁ]{3,})»?[ \t]*$",
        r"CTA[^\n]*?«([А-ЯЁ]{3,})»",
        r"слов[оа]\s+«?([А-ЯЁ]{3,})»?",
        r"CTA[^\n]*?\b([А-ЯЁ]{3,})\b",
    ]
    for pat in patterns:
        m = re.search(pat, text, re.IGNORECASE | re.MULTILINE)
        if m:
            return m.group(1).upper()
    warnings.append(
        "Кодовое слово CTA в книге не найдено (нет оборота «слово «X»»). "
        "Чужое подставлять не будем: в сценарии на его месте встанет пометка-"
        "задание. Задай своё — настройка script_code_word.")
    return DEFAULT_CODE_WORD


def _parse_hooks(text: str, warnings: list) -> list:
    """Банк хуков из секции про хуки для Reels (нумерованные строки).

    Нет секции с заголовком — банк ПУСТ (см. BUG-2026-08-08): раньше тут был
    откат на весь документ, который хватал произвольные нумерованные строки
    (в т.ч. заголовки разделов) как будто это хуки."""
    lines = text.splitlines()
    headers = _scan_headers(lines)
    idx, rank = _find_section(headers, _HOOKS_TITLE_RE)
    if idx is None:
        warnings.append(
            "Секция с хуками не найдена (ищем заголовок со словом «хук») — "
            "банк хуков пуст, сценарист использует общие заготовки модуля.")
        return []
    # Обрываем на ближайшем заголовке не глубже второго уровня — как и до
    # BUG-2026-08-10 («# ХУКИ» кончались на следующем «# » или «## »).
    end = _section_end(headers, idx, max(rank, 2), len(lines))
    hooks = []
    for line in lines[idx + 1:end]:
        mm = _ITEM_RE.match(line)
        if not mm:
            continue
        h = mm.group(1).strip()
        if "Вариаци" in h or h.startswith("31-"):
            continue
        if len(h) >= 8:
            hooks.append(h)
    if not hooks:
        warnings.append(
            "Секция с хуками найдена, но в ней не нашлось ни одной нумерованной "
            "строки-хука — банк хуков пуст.")
    return hooks


def _parse_themes_by_rubric(text: str, warnings: list) -> dict:
    """Реальные фразы клиента по рубрикам из секции про темы для постов.

    Возвращает {rubric: [phrase, ...]} в порядке файла. Рубрика — ДОСЛОВНОЕ имя
    подзаголовка «## <рубрика>» из файла клиента (см. BUG-2026-08-08): раньше
    имя матчилось на зашитый список из 7 рубрик Валерии, и рубрики другой ниши
    (здоровье, кармические сценарии, обучение...) отсеивались молча — 0 тем.
    Берём нумерованные строки внутри каждой «## <рубрика>» до следующего
    заголовка `#`/`##`. Толерантно к оформлению: кривые строки пропускаем."""
    lines = text.splitlines()
    headers = _scan_headers(lines)
    idx, rank = _find_section(headers, _THEMES_TITLE_RE)
    if idx is None:
        warnings.append(
            "Секция с темами по рубрикам не найдена (ищем заголовок со словами "
            "«тем...»+«пост...»/«рубрик...») — рубрики и темы клиента не "
            "подключены, планировщик работает на общем банке модуля.")
        return {}
    # Секция кончается на заголовке ТОГО ЖЕ уровня или выше; всё, что глубже, —
    # это её рубрики (до BUG-2026-08-10: секция «# », рубрики «## »).
    end = _section_end(headers, idx, rank, len(lines))
    subheads = {j: t for j, r, t in headers if idx < j < end and r > rank}

    themes = {}
    current = None
    for i in range(idx + 1, end):
        line = lines[i]
        if i in subheads:
            current = re.sub(r"\s+", " ", subheads[i])
            continue
        if current is None:
            continue
        mm = _ITEM_RE.match(line)
        if not mm:
            continue
        phrase = re.sub(r"\s+", " ", mm.group(1).strip())
        if len(phrase) >= 6:
            themes.setdefault(current, []).append(phrase)
    if not themes:
        warnings.append(
            "Секция с темами найдена, но в ней нет подрубрик («## <рубрика>») "
            "с нумерованными темами — рубрики и темы клиента не подключены.")
    return themes


def _parse_anchor(text: str, warnings: list) -> str:
    """Якорный кейс эксперта — короткая настоящая история, которую сценарист
    ставит в бит «кейс».

    ⚠️ Здесь до 09.08.2026 стоял поиск буквально по «136 … точ» — числу из кейса
    эксперта-донора. Чужой факт из выдачи убрали, а ПОИСК остался его: клиент
    любой другой ниши мог вписать свой кейс куда угодно, и он не находился
    никогда. Дефект тихий — сценарий просто вечно показывал пометку-задание.

    Порядок теперь такой:
      1. ЯВНАЯ ПОМЕТКА — строка «Якорный кейс: …» (или «Главный кейс», «Кейс-
         якорь»). Это то, что мы просим написать клиента: работает в любой нише,
         результат предсказуем.
      2. ЗАПАСНОЙ РАЗБОР для книг, написанных до появления пометки: строка,
         похожая на историю клиента — упоминает клиента И содержит число.
         Сработал он — предупреждаем: угадали, лучше задать явно.
    Не нашли ничего — пусто и пометка-задание в сценарии. Чужого не берём.
    """
    m = re.search(r"^[ \t]*(?:якорн\w*\s+кейс|главн\w*\s+кейс|кейс[-\s]якорь)"
                  r"[ \t]*[:：—–-][ \t]*(.+)$", text, re.IGNORECASE | re.MULTILINE)
    if m:
        found = m.group(1).strip()
        if found:
            return found.rstrip(".") + "."

    for line in text.splitlines():
        s = line.strip().lstrip("#").strip()
        s = re.sub(r"^\d+[.)]\s*", "", s)          # нумерация банка хуков
        if not (20 <= len(s) <= 220):
            continue
        if re.search(r"клиент", s, re.IGNORECASE) and re.search(r"\d", s):
            warnings.append(
                "Якорный кейс взят по догадке — строка «%s» похожа на историю "
                "клиента. Чтобы не гадать, напишите в книге смыслов отдельную "
                "строку: «Якорный кейс: …»." % (s[:60] + ("…" if len(s) > 60 else "")))
            return s.rstrip(".") + "."

    warnings.append(
        "Якорный кейс в книге не найден — поле anchor пустое. В сценарии на "
        "месте бита «кейс» встанет пометка «здесь твой кейс»: доказательство "
        "обязано быть настоящим, поэтому ни чужого, ни выдуманного тут не будет. "
        "Добавьте в книгу смыслов строку: «Якорный кейс: …».")
    return ""
