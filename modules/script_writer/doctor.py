# -*- coding: utf-8 -*-
"""doctor модуля script_writer (генератор сценариев съёмки).

Печатает ПО-РУССКИ человеческим языком, что готово и что поправить. Без
стектрейсов.

Коды выхода — СТЕПЕНЬ БЕДЫ (CONTRACT.md §2, BOX-51):
    0 — модуль полностью работоспособен: собирает валидный сценарий (хук +
        дубли + CTA) ИЗ КНИГИ СМЫСЛОВ КЛИЕНТА, кодовое слово на месте.
    2 — УРЕЗАННЫЙ РЕЖИМ: сценарий собирается, но это каркас на нейтральных
        заготовках, а не голос клиента (нет книги смыслов / она неполная),
        либо не задано кодовое слово CTA. Чинить не срочно.
    1 — НЕ ГОТОВ: сценарий не собирается вовсе (сборка падает, схема не
        проходит, умолчания невалидны) ЛИБО сама проверка не отработала.

Запуск (оба варианта):
    python -m script_writer.doctor
    python modules/script_writer/doctor.py
"""
from __future__ import annotations

import sys

try:
    from . import bible, config, model, writer
except ImportError:  # запуск файлом напрямую
    import os
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    from script_writer import bible, config, model, writer


def check():
    """Проверка модуля. Возвращает три списка:

        problems — модуль НЕ готов (код 1): сценария не будет вообще.
        limits   — УРЕЗАННЫЙ РЕЖИМ (код 2): сценарий соберётся, но это каркас
                   на нейтральных заготовках, а не контент клиента.
        lines    — наблюдения, на код возврата не влияют.
    """
    problems, limits, lines = [], [], []

    # 1. Умолчания под сценарий.
    dur = config.default_duration_sec()
    beats = config.default_beats()
    if dur <= 0 or beats < 3:
        problems.append("Некорректные умолчания сценария (длительность=%s, "
                        "битов=%s). Нужны положительные числа, битов 3–5. "
                        "Пока это так, разложить дубли по времени нельзя." % (dur, beats))
    else:
        lines.append("OK  Умолчания: ролик ~%d сек, %d смысловых бита, "
                     "драматургических арок в ротации: %d."
                     % (dur, beats, len(writer._ARCS)))

    # 2. Книга смыслов. Нет её — не поломка, но честно предупреждаем.
    #    BUG-2026-08-08: раньше «OK» здесь печаталось и тогда, когда парсер
    #    тихо подставлял дефолты Валерии вместо реальных данных клиента другой
    #    ниши. Теперь bible.load_bible() отдаёт "warnings" по каждому такому
    #    случаю — печатаем их явно как ⚠, а не прячем внутри общего «OK».
    bib = bible.load_bible()
    if bib.get("ok"):
        n_hooks = len(bib.get("hooks") or [])
        themes = bib.get("themes") or {}
        n_themes = sum(len(v) for v in themes.values())
        bib_warnings = bib.get("warnings") or []
        if bib_warnings:
            lines.append("⚠️  Книга смыслов прочитана, но с оговорками (см. ниже) — "
                         "часть полей в файле не нашлась. Чужим они не "
                         "заполняются: в сценарии останутся пометки-задания.")
        else:
            lines.append("OK  Книга смыслов прочитана: кодовое слово «%s», хуков в "
                         "банке: %d, реальных фраз по рубрикам: %d (%d рубрик: %s)."
                         % (bib.get("code_word"), n_hooks, n_themes, len(themes),
                            ", ".join(sorted(themes)) or "—"))
        for w in bib_warnings:
            lines.append("⚠️  %s" % w)
        if n_hooks == 0 and n_themes == 0 and not bib_warnings:
            lines.append("i   В книге не нашлись ни банк хуков, ни темы по "
                         "рубрикам — хук возьмётся из темы. Это допустимо.")
    else:
        # Урезанный режим, а не поломка: сценарий соберётся и снимать по нему
        # можно, но звучать он будет обобщённо — не голосом клиента.
        limits.append("Книга смыслов «%s» не найдена в корне установки — "
                      "сценарий соберётся, но это будет КАРКАС на нейтральных "
                      "заготовках, а не ваш контент: ваших формулировок, кейсов "
                      "и кодового слова в ролике не будет. Подключить одной "
                      "командой: python bible_setup.py --install"
                      % config.bible_file())

    # 2b. Банк виральной разведки — опциональное усиление хука (ЛЕВЕР 2).
    try:
        n_niche = len(writer._niche_hooks())
    except Exception:
        n_niche = 0
    if n_niche:
        lines.append("OK  Банк виральной разведки найден: %d хуков подмешиваются "
                     "в пул первой фразы." % n_niche)
    else:
        lines.append("i   Банка виральной разведки (/niche-hooks) нет — это "
                     "опциональное усиление, сценарий и без него полный.")

    # 3. Главная проверка: реально собираем сценарий и валидируем его схему.
    try:
        # Тестовая единица нейтральная: рубрика и тема одного эксперта здесь
        # означали бы, что доктор проверяет модуль на чужих данных.
        demo = writer.build_script({
            "rubric": "Кейсы",
            "topic": "История клиента: с чем пришёл и чем закончилось",
        })
        errs = model.validate(demo)
    except Exception as ex:
        problems.append("Сборка тестового сценария упала: %s. Это внутренняя "
                        "ошибка модуля, покажи строку человеку." % ex)
        errs = None

    if errs:
        problems.append("Тестовый сценарий не прошёл проверку схемы: %s"
                        % "; ".join(errs))
    elif errs is not None:
        lines.append("OK  Тестовый сценарий собран: %d дублей (хук…CTA), арка «%s»."
                     % (len(demo["shots"]), demo.get("arc", "?")))

        # ГЛАВНАЯ строка доктора. Полгода он отвечал на вопрос «модуль
        # запускается?» и печатал «Модуль готов», пока сценарии собирались из
        # чужого контента (BUG-2026-08-08). Вопрос «а это вообще про ЭТОГО
        # клиента?» никто не задавал — теперь задаёт, и числом.
        ind = demo.get("individual") or {}
        pct = int(ind.get("percent") or 0)
        todo = int(ind.get("todo") or 0)
        if pct >= 80:
            lines.append("OK  Индивидуальность: %d%% дублей собрано из вашей книги "
                         "смыслов (%d из %d)." % (pct, ind.get("from_client", 0),
                                                  ind.get("shots_total", 0)))
        elif pct > 0:
            # Порог тот же, что и для «OK» выше: меньше 80% — половину ролика
            # клиент договаривает за систему сам, это урезанный режим.
            limits.append("Индивидуальность: только %d%% дублей из вашей книги "
                          "смыслов (%d из %d) — остальное нейтральные заготовки, "
                          "и ролик звучит обобщённо, не вашим голосом. Чем полнее "
                          "книга смыслов, тем меньше вам придётся переписывать "
                          "руками." % (pct, ind.get("from_client", 0),
                                       ind.get("shots_total", 0)))
        else:
            limits.append("Индивидуальность: 0% — сценарий собран целиком на "
                          "нейтральных заготовках. Это каркас, а не ваш контент: "
                          "снимать по нему можно, но узнаваемым он не будет. "
                          "Подключите книгу смыслов: python bible_setup.py --install")
        if todo:
            limits.append("Мест-заданий в сценарии: %d (кейс и/или кодовое "
                          "слово) — их придётся дописать руками перед съёмкой. "
                          "Они оставлены пустыми намеренно: чужой кейс сюда не "
                          "подставляется. Закроются сами, как только эти строки "
                          "появятся в книге смыслов." % todo)

        if demo["code_word"]:
            lines.append("OK  Кодовое слово CTA: «%s»." % demo["code_word"])
        else:
            limits.append("Кодовое слово CTA не задано — в финале ролика будет "
                          "пометка-задание вместо призыва, и зрителю некуда "
                          "написать: заявки по ролику к вам не придут. Задайте "
                          "своё: настройка script_code_word.")

    # Заглушка «умного» шага. Реализовывать её не надо — манифест модуля прямо
    # объявляет генератор ДЕТЕРМИНИРОВАННЫМ и обещает не тратить платные API,
    # значит заявленный главный путь на месте и полон. Но молчать нельзя: человек
    # должен понимать, из чего собран его сценарий. Код возврата не поднимаем.
    lines.append("i   Сценарий собирается детерминированно — из вашей книги "
                 "смыслов и заготовок, без платного ИИ и без обращений в сеть. "
                 "Это штатный режим: «умный» шаг (writer.llm_script) намеренно "
                 "оставлен заглушкой, чтобы ваши деньги на API не тратились.")

    return problems, limits, lines


def main():
    try:
        problems, limits, lines = check()
    except Exception as ex:  # никаких стектрейсов клиенту
        print("Проверка модуля сценариев не смогла отработать: %s" % ex)
        print("Это сбой самой проверки. Покажите строку выше человеку.")
        return 1

    print("=== Проверка генератора сценариев (модуль script_writer) ===")
    for line in lines:
        print(" ", line)
    if problems:
        print()
        print("Не работает — это чинить:")
        for p in problems:
            print("  - " + p)
        if limits:
            print()
            print("Кроме того, часть возможностей недоступна:")
            for lim in limits:
                print("  - " + lim)
        return 1
    if limits:
        print()
        print("Модуль работает, но в урезанном режиме — вот чего не хватает:")
        for lim in limits:
            print("  - " + lim)
        print()
        print("Это не поломка и не срочно: сценарий вы получите уже сейчас и "
              "снимать по нему можно. Пополните книгу смыслов — и ролики "
              "зазвучат вашим голосом без правок руками.")
        return 2
    print()
    print("Модуль готов. Дай ему строку плана (рубрика + тема) — вернёт готовый "
          "сценарий по дублям: что сказать и что показать, длительность и субтитр. "
          "Ничего не публикует.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
