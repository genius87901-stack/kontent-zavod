#!/bin/sh
# ЗАВОД — запуск чего угодно из папки завода, без путей к питону (macOS/Linux).
#
# Зачем: у клиента нет обязанности знать, где лежит питон. Коробка приносит своё
# окружение, и оно вне PATH. Пускатель ищет его сам, по порядку.
#
# ⚠️ Имена переменных здесь ЛАТИНИЦЕЙ, хотя весь проект по-русски. Первая
# редакция использовала кириллическое имя, и `sh` разобрал строку как команду:
# "ЗДЕСЬ=/путь: No such file or directory". POSIX-оболочка кириллицу в именах
# переменных не обязана понимать — комментарии можно, имена нет.
#
# Использование:  ./zavod.sh github_backup.py --включи
set -e
here="$(cd "$(dirname "$0")" && pwd)"
export PYTHONIOENCODING=utf-8
export PYTHONUTF8=1

for p in "$here/.venv/bin/python3" "$here/.venv/bin/python"          "$here/python/bin/python3" python3 python; do
    if [ -x "$p" ] || command -v "$p" >/dev/null 2>&1; then
        exec "$p" "$@"
    fi
done

echo ""
echo "Не нашёл питон внутри папки завода."
echo "Похоже, завод установлен не полностью. Покажите эту строчку тому, кто ставил."
exit 1
